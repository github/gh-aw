function syntheticTemplateContext(template) {
  const values = {
    workflow_name: workflowName,
    workflow_id: "synthetic-preview",
    workflow_source: context.workflowSource,
    workflow_source_url: context.workflowSourceUrl,
    run_url: runUrl,
    run_id: "1000",
    repository: context.repository,
    owner: "synthetic",
    repo: "repository",
    issue_number: 42,
    pull_number: 43,
    branch: "synthetic-branch",
    branch_name: "synthetic-branch",
    base_branch: "main",
    title: "Synthetic pull request",
    main_body: "This is a synthetic body for a test. No GitHub item is created.",
    generated_at: "2026-01-01T00:00:00Z",
    current_minutes: 10,
    suggested_minutes: 20,
    suggested_credits: 5,
    suggested_limit: 100,
    cap: 3,
    window_hours: 24,
    category: "synthetic_outcome",
    conclusion: "warning",
    reason: "Synthetic diagnostic reason",
    reason_text: "A synthetic threat was detected.",
    files: "`synthetic/file.txt`",
    generated_footer: `> Generated by [${workflowName}](${runUrl})`,
    footer: `> Generated by [${workflowName}](${runUrl})`,
    DIFF_CONTENT: "```diff\n-old synthetic value\n+new synthetic value\n```",
    REPOSITORY: context.repository,
  };
  for (const [, key] of template.matchAll(/\{(\w+)\}/g)) {
    if (values[key] !== undefined) continue;
    if (/url$/i.test(key)) values[key] = `https://example.test/synthetic/${key}`;
    else if (/context$|section$|list$/i.test(key)) values[key] = `Synthetic ${key}.\n\n`;
    else values[key] = `synthetic_${key}`;
  }
  return values;
}

function renderMessagePreviews() {
  const core = require("./messages_core.cjs");
  const footer = require("./messages_footer.cjs");
  const status = require("./messages_run_status.cjs");
  const staged = require("./messages_staged.cjs");
  const header = require("./messages_header.cjs");
  const discussion = require("./messages_close_discussion.cjs");
  const previews = [];
  const add = (name, body) => previews.push(`## ${name}\n\n${body.trimEnd() || "_Empty by default._"}\n`);

  for (const name of ["getRunStartedMessage", "getRunSuccessMessage", "getRunFailureMessage", "getDetectionFailureMessage", "getPullRequestCreatedMessage", "getIssueCreatedMessage", "getCommitPushedMessage"]) {
    add(name, status[name](context));
  }
  for (const reason of ["threat_detected", "agent_failure", "parse_error"]) {
    add(`getDetectionWarningMessage: ${reason}`, status.getDetectionWarningMessage({ ...context, reason }));
  }
  for (const name of ["getFooterMessage", "getFooterInstallMessage", "getFooterWorkflowRecompileMessage", "getFooterWorkflowRecompileCommentMessage", "getFooterAgentFailureIssueMessage", "getFooterAgentFailureCommentMessage"]) {
    add(name, footer[name](context));
  }
  add("getStagedTitle", staged.getStagedTitle(context));
  add("getStagedDescription", staged.getStagedDescription(context));
  add("getCloseOlderDiscussionMessage", discussion.getCloseOlderDiscussionMessage(context));
  add("getBodyHeader: default", header.getBodyHeader(context));
  add("getDisclosureHeader: default", header.getDisclosureHeader(context));
  vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ disclosureHeader: true, bodyHeader: "> Synthetic header for {workflow_name}" }));
  add("getBodyHeader: configured", header.getBodyHeader(context));
  add("getDisclosureHeader: enabled", header.getDisclosureHeader(context));
  add("getBodyFooterMessage: configured", footer.getBodyFooterMessage("> Synthetic policy footer for {workflow_name}", context));
  vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", "");
  add("generateFooterWithMessages: issue or pull request", footer.generateFooterWithMessages(workflowName, runUrl, context.workflowSource, context.workflowSourceUrl, 42));
  add(
    "formatIssueBody: complete synthetic issue",
    require("./issue_body.cjs").formatIssueBody("## Synthetic finding\n\nThis is a synthetic issue body for testing, not a real report.\n\n- [x] Synthetic task completed", { repo: { owner: "synthetic", repo: "repository" } })
  );

  const files = readdirSync(promptsDirectory)
    .filter(name => name.endsWith(".md"))
    .sort();
  for (const name of instructionTemplates) expect(files).toContain(name);
  for (const name of files.filter(name => !instructionTemplates.has(name))) {
    const filename = `${promptsDirectory}/${name}`;
    let body;
    if (name === "firewall_blocked_domains.md") {
      body = require("./firewall_blocked_domains.cjs").generateBlockedDomainsSection(["api.github.com", "synthetic.example.test"], filename);
    } else {
      const template = readFileSync(filename, "utf8");
      body = core.renderTemplateFromFile(filename, syntheticTemplateContext(template));
    }
    expect(body, `Unrendered placeholder in ${name}`).not.toMatch(/\{\w+\}/);
    add(`Template: ${name}`, body);
  }
  return [
    "# Synthetic message previews",
    "",
    "Generated locally by `messages_preview.test.cjs` from synthetic test fixtures only. Nothing is published to GitHub.",
    "This file covers message generators and every bundled Markdown body/diagnostic template; agent-only instruction templates are excluded explicitly.",
    "",
    previews.join("\n---\n\n"),
  ].join("\n");
}

it("renders synthetic previews of every published message template", async () => {
  const preview = renderMessagePreviews();
  await expect(preview).toMatchFileSnapshot("./testdata/messages_preview.md");
});
