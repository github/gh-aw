// @ts-check
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import path from "path";
import { fileURLToPath } from "url";

describe("create_steering_issue", () => {
  let originalGlobals;
  let originalEnv;

  beforeEach(() => {
    originalGlobals = {
      core: global.core,
      github: global.github,
      context: global.context,
    };
    originalEnv = { ...process.env };
    global.core = { setOutput: vi.fn(), info: vi.fn() };
    global.context = {
      serverUrl: "https://github.com",
      workflow: "Fallback workflow",
      runId: 123,
      repo: { owner: "owner", repo: "repo" },
    };
    global.github = {
      rest: {
        issues: {
          create: vi.fn().mockResolvedValue({
            data: { number: 42, html_url: "https://github.com/owner/repo/issues/42" },
          }),
        },
      },
    };
    process.env.GH_AW_WORKFLOW_NAME = "Test workflow";
    process.env.GH_AW_PROMPTS_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "../md");
    for (const key of Object.keys(process.env)) {
      if (key.startsWith("GH_AW_") && key !== "GH_AW_WORKFLOW_NAME" && key !== "GH_AW_PROMPTS_DIR") {
        delete process.env[key];
      }
    }
    process.env.GITHUB_RUN_ID = "123";
  });

  afterEach(() => {
    global.core = originalGlobals.core;
    global.github = originalGlobals.github;
    global.context = originalGlobals.context;
    process.env = originalEnv;
    vi.resetModules();
  });

  it("creates a steering issue and exports its identity", async () => {
    const { main } = await import("./create_steering_issue.cjs");
    await main();

    expect(global.github.rest.issues.create).toHaveBeenCalledWith({
      owner: "owner",
      repo: "repo",
      title: "[WIP] Test workflow: work in progress",
      body: expect.stringContaining("Add a comment containing the keyword `steer`"),
    });
    expect(global.core.setOutput).toHaveBeenCalledWith("issue_number", 42);
    expect(global.core.setOutput).toHaveBeenCalledWith("issue_url", "https://github.com/owner/repo/issues/42");
  });

  it("includes generated-by attribution and RAI tracking from creation", async () => {
    process.env.GH_AW_WORKFLOW_ID = "test-workflow";
    process.env.GH_AW_TRACKER_ID = "tracker-123";
    process.env.GH_AW_ENGINE_ID = "copilot";
    process.env.GH_AW_ENGINE_VERSION = "1.0.0";
    process.env.GH_AW_ENGINE_MODEL = "gpt-5";
    global.context.payload = { issue: { number: 7 } };
    const { main } = await import("./create_steering_issue.cjs");
    await main();

    const body = global.github.rest.issues.create.mock.calls[0][0].body;
    expect(body).toContain("> Generated by [Test workflow](https://github.com/owner/repo/actions/runs/123) for #7");
    expect(body).toContain(
      "<!-- gh-aw-agentic-workflow: Test workflow, gh-aw-tracker-id: tracker-123, engine: copilot, version: 1.0.0, model: gpt-5, id: 123, workflow_id: test-workflow, run: https://github.com/owner/repo/actions/runs/123 -->"
    );
    expect(body.indexOf("> Generated by")).toBeGreaterThan(body.indexOf("Add a comment containing the keyword `steer`"));
    expect(body.match(/> Generated by/g)).toHaveLength(1);
    expect(body.match(/gh-aw-agentic-workflow:/g)).toHaveLength(1);
  });

  it("attributes WIP issues when optional metadata is unavailable", async () => {
    delete process.env.GH_AW_WORKFLOW_NAME;
    const { main } = await import("./create_steering_issue.cjs");
    await main();

    const body = global.github.rest.issues.create.mock.calls[0][0].body;
    expect(body).toContain("> Generated by [Fallback workflow](https://github.com/owner/repo/actions/runs/123)");
    expect(body).toContain("<!-- gh-aw-agentic-workflow: Fallback workflow, id: 123, run: https://github.com/owner/repo/actions/runs/123 -->");
    expect(body).not.toContain("undefined");
  });

  it("uses the configured footer while retaining tracking", async () => {
    process.env.GH_AW_SAFE_OUTPUT_MESSAGES = JSON.stringify({
      footer: "> Generated by {workflow_name}: {run_url}",
    });
    const { main } = await import("./create_steering_issue.cjs");
    await main();

    const body = global.github.rest.issues.create.mock.calls[0][0].body;
    expect(body).toContain("> Generated by Test workflow: https://github.com/owner/repo/actions/runs/123");
    expect(body).toContain("<!-- gh-aw-agentic-workflow: Test workflow, id: 123, run: https://github.com/owner/repo/actions/runs/123 -->");
  });

  it("sanitizes and truncates the title", async () => {
    process.env.GH_AW_WORKFLOW_NAME = `@team ${"A".repeat(300)}`;
    const { main } = await import("./create_steering_issue.cjs");
    await main();

    const title = global.github.rest.issues.create.mock.calls[0][0].title;
    expect(title).toHaveLength(256);
    expect(title).toMatch(/^\[WIP\] `@team` A+/);
  });
});
