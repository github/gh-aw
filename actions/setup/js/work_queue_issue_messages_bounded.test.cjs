import assert from "node:assert/strict";
import path from "node:path";
import { beforeEach, afterEach, describe, it, vi } from "vitest";
import { issueBody, issueBodyReport, issueTitle, summaryReport, claimReport } from "./work_queue_issue_messages.cjs";
import { renderSizedReport } from "./report_size.cjs";
import { sanitizeContent } from "./sanitize_content.cjs";
import { balanceCodeRegions } from "./markdown_code_region_balancer.cjs";
import { applyToNonCodeRegions } from "./sanitize_content_core.cjs";
import * as commonmark from "commonmark";

const config = { title_prefix: "Work", label: "work" };
const origin = { repository: "owner/repo", workflow: ".github/workflows/dispatcher.lock.yml", run_id: "123", run_attempt: 1 };
const workId = "a".repeat(64);

function renderPayload(value, field, maskedValues = []) {
  const work = { work_id: workId, payload: { [field]: value } };
  if (field === "title") return issueTitle(work, config, maskedValues).split(" — ")[1] || "";
  const state = { repository: origin.repository, workCreators: new Map([[workId, origin]]) };
  const body = issueBody(state, work, origin, config, "work-queue", maskedValues);
  return body.split("### Work description\n\n")[1]?.split(/\n\n+\\?\| At a glance/)[0] || "";
}

function assertSafeBounded(text, limit, literal = false) {
  assert.ok([...text].length <= limit, `Rendered ${[...text].length} code points, exceeding ${limit}`);
  if (literal) {
    const walker = new commonmark.Parser().parse(text).walker();
    let event;
    while ((event = walker.next())) {
      if (!event.entering) continue;
      assert.ok(!["html_inline", "html_block", "heading", "code_block"].includes(event.node.type));
      if (event.node.type === "text") assert.doesNotMatch(event.node.literal, /@[A-Za-z0-9]/);
    }
    return;
  }
  assert.equal(sanitizeContent(text), text);
  assert.equal(balanceCodeRegions(text), text);
  applyToNonCodeRegions(text, segment => {
    assert.doesNotMatch(segment, /@[A-Za-z0-9]/);
    return segment;
  });
}

describe("bounded Work queue Issue payload rendering", () => {
  beforeEach(() => {
    vi.stubGlobal("core", { info() {}, warning() {} });
    vi.stubEnv("GH_AW_PROMPTS_DIR", path.resolve(import.meta.dirname, "../md"));
  });
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.unstubAllEnvs();
  });

  it.each(["allowed-only", "allowed-or-code-region"])("sanitizes literal description URLs and commands before sizing under %s", policy => {
    vi.stubEnv("GH_AW_ALLOWED_DOMAINS", "github.com");
    vi.stubEnv("GH_AW_SAFE_OUTPUTS_URLS", policy);
    vi.stubEnv("GH_AW_COMMANDS", '["bot"]');
    for (const suffix of ["", "x".repeat(5000)]) {
      for (const url of ["https://outside.invalid/phish", "`https://outside.invalid/phish`", "https&#58;//outside.invalid/phish", "javascript%3Aalert(1)"]) {
        const rendered = renderPayload(`/bot ${url} ${suffix}`, "description");
        assert.doesNotMatch(rendered, /https:\/\/outside\.invalid|https&#58;|javascript%3A|javascript:/i);
        assert.ok(!rendered.startsWith("/bot"));
        assertSafeBounded(rendered, 4096, true);
      }
    }
    assert.ok(renderPayload("https://github.com/owner/repo", "description").includes("https://github.com/owner/repo"));
  });

  it.each(["issue", "summary", "claim"])("inserts exactly one attribution footer into the %s report", kind => {
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", "");
    vi.stubEnv("GH_AW_WORKFLOW_NAME", "dispatcher");
    const state = { repository: origin.repository, workCreators: new Map([[workId, origin]]) };
    const report =
      kind === "issue"
        ? issueBodyReport(state, { work_id: workId, payload: {} }, origin, config, "work-queue")
        : kind === "summary"
          ? summaryReport({ work_id: workId, ledger_url: "https://github.com/owner/repo/blob/work-queue/work-queue.jsonl", outcome_links: [], diagnostics: [], claim_history: [] }, origin, "Queued")
          : claimReport({ claim_id: "claim", claim_handle: "claim-handle", run_url: "https://github.com/owner/repo/actions/runs/123", outcome: "running", diagnostics: [] }, origin);
    const body = renderSizedReport(report).body;
    assert.equal(body.match(/Generated by /g)?.length, 1);
    assert.equal(body.match(/<!-- gh-aw-agentic-workflow:/g)?.length, 1);
    assert.ok(!body.includes("{generated_footer}"));
  });

  for (const [field, limit] of [
    ["title", 128],
    ["description", 4096],
  ]) {
    describe(field, () => {
      it("retains exact-boundary Unicode text without splitting surrogate pairs", () => {
        const value = "😀".repeat(limit);
        assert.equal(renderPayload(value, field), value);
        const truncated = renderPayload(`${value}🧑‍💻 more`, field);
        assertSafeBounded(truncated, limit, field === "description");
        assert.ok(truncated.includes("..."));
        assert.doesNotMatch(truncated, /[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/u);
      });

      it("keeps neutralizing delimiters intact for a long mention crossing the boundary", () => {
        const value = "z".repeat(limit - 24) + " @alice-bob-longname rest words to go over the limit for sure";
        const rendered = renderPayload(value, field);
        assertSafeBounded(rendered, limit, field === "description");
        assert.ok(rendered.includes("@alice"));
        assert.ok(rendered.includes("..."));
      });

      for (const fence of ["```", "~~~~", "``````"]) {
        it(`balances an unmatched ${fence.length}-character fence within the final limit`, () => {
          const rendered = renderPayload(`${fence}\n${"x".repeat(limit * 2)} @alice`, field);
          assertSafeBounded(rendered, limit, field === "description");
          if (field === "description") {
            assert.ok(rendered.startsWith([...fence].map(character => `\\${character}`).join("")));
            assert.ok(!rendered.endsWith(`\n${fence}`));
          } else {
            assert.ok(rendered.startsWith(fence));
            assert.ok(rendered.endsWith(`\n${fence}`));
          }
        });
      }

      for (const delimiter of ["`", "``"]) {
        it(`safely renders a mention after truncating a ${delimiter.length}-backtick inline span`, () => {
          const value = `${delimiter}${"x".repeat(limit - 32)} @alice-bob-longname ${"tail ".repeat(20)}${delimiter}`;
          const rendered = renderPayload(value, field);
          assertSafeBounded(rendered, limit, field === "description");
          assert.ok(rendered.includes("@alice"));
        });
      }

      it("retains built-in redaction before truncating a credential at the boundary", () => {
        const credential = `ghp_${"A".repeat(36)}`;
        const rendered = renderPayload(`${credential} ${"x".repeat(limit - 60)} ${credential} trailing text beyond the boundary`, field);
        assertSafeBounded(rendered, limit, field === "description");
        assert.ok(rendered.includes(field === "description" ? "\\*\\*\\*REDACTED\\*\\*\\*" : "***REDACTED***"));
        assert.ok(!rendered.includes("ghp_"));
      });

      it("retains exact-value redaction before truncating a mask at the boundary", () => {
        const secret = "opaque-runtime-secret-with-no-token-pattern";
        const rendered = renderPayload(`${"x".repeat(limit - 12)} ${secret} more`, field, [secret]);
        assertSafeBounded(rendered, limit, field === "description");
        assert.ok(!rendered.includes("opaque"));
      });

      it("redacts exact masks before whitespace normalization", () => {
        const secret = "opaque-runtime\nsecret-with-whitespace";
        const rendered = renderPayload(`${secret} ${"x".repeat(limit * 2)}`, field, [secret]);
        assertSafeBounded(rendered, limit, field === "description");
        assert.ok(!rendered.includes("opaque"));
        assert.ok(rendered.includes(field === "description" ? "\\*\\*\\*" : "***"));
      });

      it("redacts encoded credentials before selecting a prefix", () => {
        const credential = `ghp_${"A".repeat(36)}`;
        const encoded = credential.replace("g", "&#103;");
        const rendered = renderPayload(`${"x".repeat(limit - 20)} ${encoded} trailing text`, field);
        assertSafeBounded(rendered, limit, field === "description");
        assert.ok(!rendered.includes("ghp_"));
        assert.ok(!rendered.includes("&#103;"));
      });
    });
  }
});
