// @ts-check
import { beforeEach, describe, expect, it, vi } from "vitest";
import { expectExecutionProvenance, useExecutionProvenanceFixture } from "./test_execution_provenance.js";

useExecutionProvenanceFixture();

const request = vi.fn();
const main = require("./add_security_advisory_comment.cjs").main;
const tokenConfig = { "github-token": "external-token" };
const comment = { ghsa_id: "GHSA-2345-6789-cfgh", body: "The proposed fix is ready for maintainer review." };
const created = { id: 17, html_url: "https://github.com/test-owner/test-repo/security/advisories/GHSA-2345-6789-cfgh#advisory-comment-17" };

describe("add_security_advisory_comment", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    global.core = { info: vi.fn(), warning: vi.fn(), error: vi.fn() };
    global.context = { repo: { owner: "test-owner", repo: "test-repo" }, payload: {}, runId: 12345 };
    global.github = { request, rest: { issues: { createComment: vi.fn() } } };
    global.getOctokit = vi.fn(() => global.github);
    request.mockResolvedValue({ data: created });
  });

  it("uses the external token and advisory comment endpoint with attribution", async () => {
    const handler = await main(tokenConfig);
    expect(await handler(comment)).toEqual({ success: true, comment_id: created.id, url: created.html_url });
    expect(global.getOctokit).toHaveBeenCalledWith("external-token", expect.any(Object));
    expect(request).toHaveBeenCalledWith(
      "POST /repos/{owner}/{repo}/security-advisories/{ghsa_id}/comments",
      expect.objectContaining({ owner: "test-owner", repo: "test-repo", ghsa_id: comment.ghsa_id, headers: { "X-GitHub-Api-Version": "2026-03-10" } })
    );
    expect(request.mock.calls[0][1].body).toContain(comment.body);
    expect(request.mock.calls[0][1].body).toContain("> Generated by");
    expectExecutionProvenance(request.mock.calls[0][1].body);
    expect(global.github.rest.issues.createComment).not.toHaveBeenCalled();
  });

  it("never forwards agent repository, publication, visibility, or credential controls", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...comment, owner: "other", repo: "public", state: "published", confidential: true, "github-token": "agent-token" });
    const payload = request.mock.calls[0][1];
    expect(payload.owner).toBe("test-owner");
    expect(payload.repo).toBe("test-repo");
    expect(payload.state).toBeUndefined();
    expect(payload.confidential).toBeUndefined();
    expect(payload["github-token"]).toBeUndefined();
  });

  it("rejects missing credentials rather than using the ambient Actions token", async () => {
    await expect(main()).rejects.toThrow("requires an external github-token or GitHub App token");
    expect(request).not.toHaveBeenCalled();
  });

  it("previews without credentials, API calls, or comment content in logs", async () => {
    const handler = await main({ staged: true });
    expect(await handler(comment)).toEqual({ success: true, staged: true });
    expect(global.getOctokit).not.toHaveBeenCalled();
    expect(request).not.toHaveBeenCalled();
    expect(JSON.stringify(global.core.info.mock.calls)).not.toContain(comment.body);
  });

  it("enforces max without creating another comment", async () => {
    const handler = await main(tokenConfig);
    await handler(comment);
    expect(await handler(comment)).toMatchObject({ success: false, skipped: true, reasonCode: "MAX_COUNT_REACHED" });
    expect(request).toHaveBeenCalledTimes(1);
  });

  it.each([{ ghsa_id: "" }, { ghsa_id: "../issues/123" }, { ghsa_id: "CVE-2026-1234" }, { ghsa_id: 17 }, { body: "" }, { body: " " }, { body: "x".repeat(65001) }])("rejects invalid advisory comments: %j", async fields => {
    const handler = await main(tokenConfig);
    await expect(handler({ ...comment, ...fields })).rejects.toThrow("add_security_advisory_comment");
    expect(request).not.toHaveBeenCalled();
  });

  it("sanitizes comments and supports disabling attribution while preserving configured policy", async () => {
    const handler = await main({ ...tokenConfig, footer: false, body_footer: "Maintainer review is required." });
    await handler({ ...comment, body: "Review\u0000 this fix." });
    const body = request.mock.calls[0][1].body;
    expect(body).not.toContain("\u0000");
    expect(body).not.toContain("> Generated by");
    expect(body).toContain("Maintainer review is required.");
  });

  it("fits the complete report within the comment limit while preserving attribution", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...comment, body: "x".repeat(65000) });
    const body = request.mock.calls[0][1].body;
    expect(body.length).toBeLessThanOrEqual(65000);
    expect(body).toContain("> Generated by");
  });

  it("keeps the attribution outside agent-controlled code fences", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...comment, body: "```text\nunclosed agent content" });
    expect(request.mock.calls[0][1].body).toMatch(/unclosed agent content\n```\n[\s\S]*> Generated by/);
  });

  it("reports API failures without disclosing comment contents, retrying, or falling back to issues", async () => {
    request.mockRejectedValueOnce(Object.assign(new Error(comment.body), { status: 403 }));
    const handler = await main(tokenConfig);
    const result = await handler(comment);
    expect(result).toMatchObject({ success: false, error: expect.stringContaining("HTTP 403") });
    expect(result.error).not.toContain(comment.body);
    expect(request).toHaveBeenCalledTimes(1);
    expect(global.github.rest.issues.createComment).not.toHaveBeenCalled();
  });

  it("does not report success when GitHub omits the created comment identity", async () => {
    request.mockResolvedValueOnce({ data: {} });
    const handler = await main(tokenConfig);
    expect(await handler(comment)).toMatchObject({ success: false });
  });
});
