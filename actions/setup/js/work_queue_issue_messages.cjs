// @ts-check
"use strict";

const { sanitizeContent } = require("./sanitize_content.cjs");
const { buildFooterBlocks, getAgenticWorkflowMetadata } = require("./messages_footer.cjs");
const { stripExecutionProvenance } = require("./execution_provenance.cjs");

const ISSUE_MARKER = /<!-- gh-aw-work-queue-issue:([^\s>]+) -->/;

/** Single-line, sanitized, backtick-free inline text. @param {unknown} value */
function inline(value) {
  return sanitizeContent(
    stripExecutionProvenance(String(value), { stripGroupingMarkers: true })
      .replace(/[`\r\n]+/g, " ")
      .trim()
  );
}

/** Work id recorded in an Issue body, or undefined. @param {unknown} body */
function markedWorkId(body) {
  return typeof body === "string" ? body.match(ISSUE_MARKER)?.[1] : undefined;
}

/** Idempotence marker of a projection comment. @param {string} workId @param {string} state */
function commentMarker(workId, state) {
  return `<!-- gh-aw-work-queue:${workId}:${state} -->`;
}

/** @param {any} subject */
function subjectLabel(subject) {
  if (!subject) return undefined;
  return `${subject.repository}#${subject.number}`;
}

/** @param {any} work @param {{title_prefix: string}} config */
function issueTitle(work, config) {
  return `${config.title_prefix} ${inline(subjectLabel(work.subject) ?? work.node_key)}`.slice(0, 256);
}

/** @param {any} context @param {string} [runUrl] @returns {import("./report_ast.cjs").ReportBlock[]} */
function workQueueFooter(context, runUrl = "") {
  const workflowName = process.env.GH_AW_WORKFLOW_NAME || context.workflow || process.env.GITHUB_WORKFLOW || "Work queue";
  if (!runUrl) {
    const server = (context.serverUrl || process.env.GITHUB_SERVER_URL || "https://github.com").replace(/\/+$/, "");
    const runId = context.runId || process.env.GITHUB_RUN_ID;
    const attempt = context.runAttempt || process.env.GITHUB_RUN_ATTEMPT;
    runUrl = `${server}/${context.repo.owner}/${context.repo.repo}/actions/runs/${runId}${attempt ? `/attempts/${attempt}` : ""}`;
  }
  const [workflow, ...fields] = getAgenticWorkflowMetadata(workflowName, runUrl);
  return [
    ...buildFooterBlocks([{ type: "quote_line", children: [literal("Generated by "), { type: "link", url: runUrl, children: [literal(workflowName)], agentTainted: false }] }]),
    { type: "xml_marker", name: workflow.key, value: workflow.value, fields, agentTainted: false },
  ];
}

/** @param {string} value @param {"text"|"code"} [type] @returns {import("./report_ast.cjs").ReportInline} */
function literal(value, type = "text") {
  return { type, value, agentTainted: false };
}

/** @param {string} value @param {"text"|"code"} [type] @returns {import("./report_ast.cjs").ReportInline} */
function ledgerValue(value, type = "code") {
  return { type, value: inline(value), agentTainted: true };
}

/** @param {import("./report_ast.cjs").ReportInline[]} children @returns {import("./report_ast.cjs").ReportBlock} */
function paragraph(...children) {
  return { type: "paragraph", children, agentTainted: false };
}

/** @param {string} name @param {string} value @returns {import("./report_ast.cjs").ReportBlock} */
function marker(name, value) {
  return { type: "xml_marker", name, value, compact: true, agentTainted: false };
}

/** @param {any} work @param {string} repository @returns {import("./report_ast.cjs").ReportBlock[]} */
function issueBody(work, repository) {
  const items = [
    [paragraph(literal("Pool: "), ledgerValue(work.pool))],
    [paragraph(literal("Graph: "), ledgerValue(work.graph_id))],
    [paragraph(literal("Node: "), ledgerValue(work.node_key))],
    [paragraph(literal("Work: "), ledgerValue(work.work_id))],
  ];
  if (work.subject) {
    const repository = inline(work.subject.repository);
    const number = String(work.subject.number);
    if (/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository) && /^[1-9]\d*$/.test(number)) {
      items.push([paragraph(literal("Subject: "), ledgerValue(repository, "text"), { type: "issue_reference", number, agentTainted: true })]);
    } else {
      items.push([paragraph(literal("Subject: "), ledgerValue(subjectLabel(work.subject) ?? ""))]);
    }
  }
  return [
    paragraph(literal("This Issue tracks work queue Work.")),
    { type: "list", ordered: false, items, agentTainted: false },
    paragraph({ type: "link", url: `https://github.com/${repository}/blob/work-queue/work-queue.jsonl`, children: [literal("View the work queue ledger")], agentTainted: false }),
    marker("gh-aw-work-queue-issue", work.work_id),
  ];
}

/** @param {any} work @param {any} claim @param {any} dispatch @param {string} repository */
function claimComment(work, claim, dispatch, repository) {
  const run = `https://github.com/${repository}/actions/runs/${dispatch.run.run_id}/attempts/${dispatch.run.run_attempt}`;
  return [
    paragraph(
      literal("Claimed by dispatch "),
      ledgerValue(dispatch.dispatch_id),
      literal(` (attempt ${work.attempts + 1}); worker `),
      { type: "link", url: run, children: [literal(`run ${dispatch.run.run_id}`)], agentTainted: false },
      literal(".")
    ),
    marker("gh-aw-work-queue", `${work.work_id}:claim-${claim.claim_id}`),
  ];
}

/** @param {any} work */
function terminalComment(work) {
  const outcome = work.state === "completed" ? paragraph(literal("Work completed.")) : paragraph(literal("Work cancelled ("), ledgerValue(work.cancellation_reason), literal(")."));
  return [outcome, marker("gh-aw-work-queue", `${work.work_id}:${work.state}`)];
}

/** @param {string} workId */
function orphanComment(workId) {
  return [paragraph(literal("This Issue tracks Work that is no longer in the work queue ledger; closing it.")), marker("gh-aw-work-queue", `${workId}:orphaned`)];
}

module.exports = { claimComment, commentMarker, issueBody, issueTitle, markedWorkId, orphanComment, terminalComment, workQueueFooter };
