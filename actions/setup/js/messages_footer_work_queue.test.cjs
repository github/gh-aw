// @ts-check
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { createRequire } from "module";
import path from "path";
import { fileURLToPath } from "url";
import { useExecutionProvenanceFixture } from "./test_execution_provenance.js";

const require = createRequire(import.meta.url);
const { withClaimExecution, assertClaimAuthorized } = require("./work_queue_claim_scope.cjs");
const { getFooterMessage, generateFooterWithMessages, generateXMLMarker } = require("./messages_footer.cjs");
const { setCollectedMissings, getMissingInfoSections } = require("./missing_messages_helper.cjs");
const { assembleMarkdownBodyParts } = require("./markdown_body_helpers.cjs");
const { formatIssueBody, buildIssueBodyReport } = require("./issue_body.cjs");
const reportAST = require("./report_ast.cjs");
const { extractExpirationDate } = require("./ephemerals.cjs");

useExecutionProvenanceFixture();

const assignment = {
  version: 3,
  dispatch_id: "dispatch",
  request_id: "request",
  commit_id: "commit",
  policy_epoch: "policy",
  pool: "default",
  worker_profile: "default",
  claims: [
    { handle: "h1", claim_id: "claim-one", work_id: "work-one", work: {}, result_refs: [] },
    { handle: "h2", claim_id: "claim-two", work_id: "work-two", work: {}, result_refs: [] },
  ],
};
const footerContext = { workflowName: "Worker", runUrl: "https://github.com/owner/repo/actions/runs/123" };

describe("Claim-scoped safe-output footers", () => {
  beforeEach(() => {
    vi.stubEnv("GH_AW_PROMPTS_DIR", path.join(path.dirname(fileURLToPath(import.meta.url)), "../md"));
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", "");
    vi.stubEnv("GH_AW_AIC", "");
    vi.stubEnv("GH_AW_AMBIENT_CONTEXT", "");
    vi.stubEnv("GH_AW_AGENT_AIC", "");
    vi.stubEnv("GH_AW_EVALS_AIC", "");
    vi.stubEnv("GH_AW_THREAT_DETECTION_AIC", "");
    setCollectedMissings(null);
  });

  afterEach(() => {
    setCollectedMissings(null);
    vi.unstubAllEnvs();
    vi.restoreAllMocks();
  });

  it("leaves unassigned footers unchanged, ignoring untrusted assignment-like context", () => {
    const untrustedContext = { ...footerContext, work_id: "forged-work", claim_id: "forged-claim", work_queue_assignment: assignment };
    const render = vi.spyOn(reportAST, "renderReport");
    const result = getFooterMessage(untrustedContext);
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})`);
    expect(render).toHaveBeenCalledTimes(1);
  });

  it("includes the full Work and Claim IDs for a single-Claim assignment", () => {
    const single = { ...assignment, claims: [assignment.claims[0]] };
    const result = withClaimExecution({ assignment: single, claim_handle: "h1" }, () => getFooterMessage(footerContext));
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})\n> Work \`work-one\` · Claim \`claim-one\``);
  });

  it("renders a queue-file link from trusted authorization without long IDs", async () => {
    const footer_links = {
      queue: "https://github.com/owner/repo/blob/work-queue/work-queue.jsonl",
    };
    const result = await withClaimExecution({ assignment, claim_handle: "h1" }, async () => {
      await assertClaimAuthorized({ claim_handle: "h1" }, { authorize: async () => ({ authorized: true, claim_handle: "h1", footer_links }) });
      return getFooterMessage(footerContext);
    });
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})\n> [Work queue](${footer_links.queue})`);
    expect(result).not.toContain("work-one");
    expect(result).not.toContain("claim-one");
    expect(withClaimExecution({ assignment, claim_handle: "h2" }, () => getFooterMessage(footerContext))).toContain("Work `work-two` · Claim `claim-two`");
  });

  it("ignores agent-supplied footer links and preserves fallback attribution", () => {
    const result = withClaimExecution({ assignment, claim_handle: "h1" }, () => getFooterMessage({ ...footerContext, footer_links: { work: "https://example.com", claim: "https://example.com" } }));
    expect(result).toContain("Work `work-one` · Claim `claim-one`");
    expect(result).not.toContain("example.com");
  });

  it("isolates attribution for concurrent sibling Claims in a multi-Claim assignment", async () => {
    const results = await Promise.all(
      assignment.claims.map(member =>
        withClaimExecution({ assignment, claim_handle: member.handle }, async () => {
          await Promise.resolve();
          return getFooterMessage(footerContext);
        })
      )
    );
    for (const [index, member] of assignment.claims.entries()) {
      expect(results[index]).toContain(`> Work \`${member.work_id}\` · Claim \`${member.claim_id}\``);
      const sibling = assignment.claims[1 - index];
      expect(results[index]).not.toContain(sibling.work_id);
      expect(results[index]).not.toContain(sibling.claim_id);
    }
    expect(getFooterMessage(footerContext)).not.toContain("> Work");
  });

  it("appends Claim attribution to custom footers before run-again hints", () => {
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ footer: "> Custom {workflow_name}" }));
    const render = vi.spyOn(reportAST, "renderReport");
    const result = withClaimExecution({ assignment, claim_handle: "h2" }, () => getFooterMessage({ ...footerContext, slashCommand: "retry", labelCommand: "retry-worker" }));
    expect(result).toBe("> Custom Worker\n> Work `work-two` · Claim `claim-two`\n> <sub>Comment <em>/retry</em> to run again</sub>\n> <sub>Add label <em>retry-worker</em> to run again</sub>");
    expect(render).toHaveBeenCalledTimes(1);
    const report = render.mock.calls[0][0];
    expect(report).toMatchObject({ type: "report", title: "Footer", children: [{ type: "quote" }] });
    expect(JSON.stringify(report)).toContain('"type":"code","value":"work-two"');
    expect(JSON.stringify(report)).toContain('"type":"code","value":"claim-two"');
  });

  it.each(["", "\n"])("imports custom template markup with trailing newline %j before a single rendered Claim", trailingNewline => {
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ footer: `<details><summary>{workflow_name}</summary>\n<em>Custom</em>\n</details>${trailingNewline}` }));
    const render = vi.spyOn(reportAST, "renderReport");
    const member = { ...assignment.claims[0], work_id: "`@copilot <b>{workflow_name}</b>`", claim_id: "claim``[link](https://example.com)" };
    const special = { ...assignment, claims: [member] };
    const result = withClaimExecution({ assignment: special, claim_handle: "h1" }, () => getFooterMessage({ ...footerContext, slashCommand: "retry", labelCommand: "retry-worker" }));
    expect(result).toBe(
      "<details>\n<summary>Worker</summary>\n\n*Custom*\n\n</details>\n\n> Work `` `@copilot <b>{workflow_name}</b>` `` · Claim ```claim``[link](https://example.com)```\n> <sub>Comment <em>/retry</em> to run again</sub>\n> <sub>Add label <em>retry-worker</em> to run again</sub>"
    );
    expect(render).toHaveBeenCalledTimes(1);
  });

  it("preserves triggering context, metrics, and history alongside Claim attribution", () => {
    vi.stubEnv("GH_AW_AIC", "12.4");
    const result = withClaimExecution({ assignment, claim_handle: "h1" }, () => getFooterMessage({ ...footerContext, triggeringNumber: 42, historyUrl: "https://github.com/search?q=worker" }));
    expect(result).toContain(" for #42");
    expect(result).toContain("~13 AIC");
    expect(result).toContain("[◷](https://github.com/search?q=worker)");
    expect(result).toContain("> Work `work-one` · Claim `claim-one`");
  });

  it("renders identifier punctuation as inert code without reinterpreting template placeholders", () => {
    const member = { ...assignment.claims[0], work_id: "`@copilot <b>{workflow_name}</b>`", claim_id: "claim``[link](https://example.com)" };
    const special = { ...assignment, claims: [member] };
    const result = withClaimExecution({ assignment: special, claim_handle: "h1" }, () => getFooterMessage(footerContext));
    expect(result).toContain("`` `@copilot <b>{workflow_name}</b>` ``");
    expect(result).toContain("```claim``[link](https://example.com)```");
    expect(result).not.toContain("<b>Worker</b>");
  });

  it("uses the shared footer for generated issue bodies", () => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    try {
      const body = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" } }));
      expect(body).toContain("> Work `work-two` · Claim `claim-two`");
      expect(body).not.toContain("work-one");
      expect(body).toContain("<!-- gh-aw-execution:");
      const noFooter = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" }, footer: false }));
      expect(noFooter).not.toContain("> Work");
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it.each([false, true])("preserves paired body-header and body-footer wrappers with footer=%s", footer => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ bodyHeader: "<details><summary>Full report</summary>", footer: "> Custom" }));
    try {
      const report = withClaimExecution({ assignment, claim_handle: "h2" }, () => buildIssueBodyReport("Finding", "## Evidence\n\nIssue content", { repo: { owner: "owner", repo: "repo" }, bodyFooter: "</details>", footer }));
      expect(report.children[0]).toMatchObject({
        type: "details",
        summary: "Full report",
        children: [{ type: "heading" }, { type: "paragraph", children: [{ type: "text", value: "Issue content" }] }, ...(footer ? [{ type: "quote" }] : [])],
      });
      const { body } = reportAST.renderReport(report);
      const wrapper = footer
        ? "<details>\n<summary>Full report</summary>\n\n### Evidence\n\nIssue content\n\n> Custom\n> Work `work-two` · Claim `claim-two`\n\n</details>"
        : "<details>\n<summary>Full report</summary>\n\n### Evidence\n\nIssue content\n\n</details>";
      expect(body.startsWith(wrapper + "\n\n<!-- gh-aw-workflow-id:")).toBe(true);
      expect(body).not.toContain("&lt;/details&gt;");
      expect(body.match(/<!-- gh-aw-execution:/g)).toHaveLength(1);
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it.each([
    ["> Custom {workflow_name}", "> Custom Worker"],
    ["> First paragraph\n>\n> Second paragraph", "> First paragraph\n>\n> Second paragraph"],
  ])("keeps Claim attribution and run-again hints in the same quote for %s", (footer, renderedFooter) => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    vi.stubEnv("GH_AW_WORKFLOW_NAME", "Worker");
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ footer }));
    vi.stubEnv("GH_AW_COMMANDS", '["retry"]');
    vi.stubEnv("GH_AW_LABEL_COMMANDS", '["retry-worker"]');
    try {
      const body = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" } }));
      const footerEnd = body.indexOf("\n\n<!-- gh-aw-workflow-id:");
      expect(body.slice(0, footerEnd)).toBe(`Issue content\n\n${renderedFooter}\n> Work \`work-two\` · Claim \`claim-two\`\n> <sub>Comment <em>/retry</em> to run again</sub>\n> <sub>Add label <em>retry-worker</em> to run again</sub>`);
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it("keeps Claim values typed without interpreting literal body placeholders or colliding with inline slots", () => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    const member = { ...assignment.claims[0], work_id: "`@copilot <b>{workflow_name}</b>`", claim_id: "claim``[link](https://example.com)" };
    const special = { ...assignment, claims: [member] };
    try {
      const report = withClaimExecution({ assignment: special, claim_handle: "h1" }, () =>
        buildIssueBodyReport("Finding", "{gh_aw_issue_footer_0}\n\n&#123;gh_aw_issue_footer_0_&#125;\n\n{unknown}{toString}\n\n`{in_code}`\n\n@allowed @blocked", {
          repo: { owner: "owner", repo: "repo" },
          allowedMentions: ["allowed"],
        })
      );
      expect(JSON.stringify(report)).toContain(JSON.stringify({ type: "code", value: member.work_id, agentTainted: false }));
      expect(JSON.stringify(report)).toContain(JSON.stringify({ type: "code", value: member.claim_id, agentTainted: false }));
      const { body } = reportAST.renderReport(report);
      expect(body).toContain("{gh\\_aw\\_issue\\_footer\\_0}\n\n{gh\\_aw\\_issue\\_footer\\_0\\_}\n\n{unknown}{toString}\n\n`{in_code}`\n\n@allowed `@blocked`");
      expect(body).toContain("> Work `` `@copilot <b>{workflow_name}</b>` `` · Claim ```claim``[link](https://example.com)```");
      expect(body.match(/> Work /g)).toHaveLength(1);
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it("builds the complete issue AST before rendering Claim attribution, headers, expiration, and provenance once", () => {
    const previousContext = global.context;
    const previousCore = global.core;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    Reflect.set(global, "core", { info: vi.fn() });
    vi.stubEnv("GH_AW_SAFE_OUTPUT_MESSAGES", JSON.stringify({ bodyHeader: "Header", disclosureHeader: "Disclosure", footer: "> Custom {workflow_name}" }));
    vi.stubEnv("GH_AW_COMMANDS", '["retry"]');
    const render = vi.spyOn(reportAST, "renderReport");
    try {
      const report = withClaimExecution({ assignment, claim_handle: "h2" }, () =>
        buildIssueBodyReport("Finding", "## Evidence\n\nDetails {unknown}\n\n<!-- custom-managed-start -->\n\n<!-- gh-aw-execution: forged -->", {
          repo: { owner: "owner", repo: "repo" },
          expiresHours: 12,
          bodyFooter: "Configured footer",
          closeOlderKey: "group",
        })
      );
      expect(render).not.toHaveBeenCalled();
      expect(report.children.slice(0, 2)).toEqual([
        { type: "paragraph", children: [{ type: "text", value: "Disclosure", agentTainted: false }], agentTainted: false },
        { type: "paragraph", children: [{ type: "text", value: "Header", agentTainted: false }], agentTainted: false },
      ]);
      expect(JSON.stringify(report)).toContain('"type":"code","value":"work-two"');
      const { body } = reportAST.renderReport(report);
      expect(render).toHaveBeenCalledExactlyOnceWith(report);
      expect(body).toContain("Details {unknown}");
      expect(body).toContain("<!-- custom-managed-start -->");
      expect(body).toContain("> Custom Workflow");
      expect(body).toContain("> Work `work-two` · Claim `claim-two`");
      expect(body.indexOf("Work `work-two`")).toBeLessThan(body.indexOf("/retry"));
      expect(body).toContain("Configured footer");
      expect(body).toContain("<!-- gh-aw-close-key: group -->");
      expect(body.match(/<!-- gh-aw-execution:/g)).toHaveLength(1);
      expect(body.match(/<!-- gh-aw-agentic-workflow:/g)).toHaveLength(1);
      expect(body).not.toContain("forged");
      expect(extractExpirationDate(body)).not.toBeNull();
    } finally {
      Reflect.set(global, "context", previousContext);
      Reflect.set(global, "core", previousCore);
    }
  });

  it("uses the same attribution for PR footer assembly and respects disabled footers", () => {
    for (const includeFooter of [true, false]) {
      const parts = withClaimExecution({ assignment, claim_handle: "h1" }, () => assembleMarkdownBodyParts({ ...footerContext, includeFooter }));
      if (includeFooter) expect(parts.footer).toContain("> Work `work-one` · Claim `claim-one`");
      else expect(parts.footer).toBe("");
    }
  });

  it("emits Claim attribution once in the complete generated footer", () => {
    const render = vi.spyOn(reportAST, "renderReport");
    const result = withClaimExecution({ assignment, claim_handle: "h1" }, () => generateFooterWithMessages(footerContext.workflowName, footerContext.runUrl, "", "", undefined, undefined, undefined));
    expect(result.match(/> Work /g)).toHaveLength(1);
    expect(result).toContain("<!-- gh-aw-agentic-workflow:");
    expect(render).toHaveBeenCalledTimes(1);
  });

  it("does not render AST fragments in a complete generated footer without a Claim", () => {
    vi.stubEnv("GITHUB_RUN_ID", "");
    vi.stubEnv("GH_AW_WORKFLOW_ID", "");
    const render = vi.spyOn(reportAST, "renderReport");
    const result = generateFooterWithMessages(footerContext.workflowName, footerContext.runUrl, "", "", undefined, undefined, undefined);
    expect(result).toBe(`> Generated by [Worker](${footerContext.runUrl})\n\n<!-- gh-aw-agentic-workflow: Worker, run: ${footerContext.runUrl} -->\n`);
    expect(render).toHaveBeenCalledTimes(1);
  });

  it.each([false, true])("renders complete diagnostic footer trees once with Claim=%s", withClaim => {
    setCollectedMissings({
      missingTools: [{ tool: "docker", reason: "Need containers", alternatives: "Use podman" }],
      missingData: [{ data_type: "credentials", reason: "Missing token", context: "Private API", alternatives: "Public API" }],
      noopMessages: [{ message: "No further action" }],
      reportIncomplete: [{ reason: "Timed out", details: "Tests not finished" }],
    });
    const invoke = callback => (withClaim ? withClaimExecution({ assignment, claim_handle: "h1" }, callback) : callback());
    const expected = invoke(() => getFooterMessage(footerContext)) + getMissingInfoSections() + "\n\n" + generateXMLMarker(footerContext.workflowName, footerContext.runUrl) + "\n";
    const render = vi.spyOn(reportAST, "renderReport");
    const result = invoke(() => generateFooterWithMessages(footerContext.workflowName, footerContext.runUrl, "", "", undefined, undefined, undefined));
    expect(result.replace(/\n[ \t]*\n/g, "\n")).toBe(expected.replace(/\n[ \t]*\n/g, "\n"));
    expect(render).toHaveBeenCalledTimes(1);
  });

  it("protects Claim attribution while redacting collected diagnostic payloads", () => {
    const previousContext = global.context;
    Reflect.set(global, "context", { repo: { owner: "owner", repo: "repo" }, runId: 123, payload: {} });
    setCollectedMissings({
      missingTools: [{ tool: "SECRETOOL", reason: "SECRETREASON" }],
      missingData: [],
      reportIncomplete: [],
    });
    try {
      const body = withClaimExecution({ assignment, claim_handle: "h2" }, () => formatIssueBody("Issue content", { repo: { owner: "owner", repo: "repo" }, redact: () => true }));
      expect(body).toContain("> Work `work-two` · Claim `claim-two`");
      expect(body).toContain("<summary>Missing Tools</summary>");
      expect(body).not.toContain("SECRETOOL");
      expect(body).not.toContain("SECRETREASON");
      expect(body).not.toContain("Issue content");
    } finally {
      Reflect.set(global, "context", previousContext);
    }
  });

  it("keeps arbitrary diagnostic Markdown as literal typed data", () => {
    const nested = "HOSTILE\n" + Array.from({ length: 64 }, (_, depth) => "  ".repeat(depth + 1) + "- NESTED").join("\n");
    setCollectedMissings({
      missingTools: [{ tool: "docker", reason: nested, alternatives: "~~~\n</details>\n<details><summary>HOSTILE</summary>" }],
      missingData: [{ data_type: "data", reason: nested, context: nested, alternatives: nested }],
      noopMessages: [{ message: nested }],
      reportIncomplete: [{ reason: nested, details: nested }],
    });
    const { parseReportMarkdown } = require("./report_markdown.cjs");
    expect(() => parseReportMarkdown(getMissingInfoSections())).toThrow("Report template nesting exceeds the maximum depth");
    const render = vi.spyOn(reportAST, "renderReport");
    const result = generateFooterWithMessages(footerContext.workflowName, footerContext.runUrl, "", "", undefined, undefined, undefined);
    expect(result).toContain("HOSTILE");
    expect(result).not.toContain("<summary>HOSTILE</summary>");
    expect(result.match(/<summary>Missing Tools<\/summary>/g)).toHaveLength(1);
    expect(result).toContain(generateXMLMarker(footerContext.workflowName, footerContext.runUrl));
    expect(render).toHaveBeenCalledTimes(1);
  });
});
