// @ts-check
import { beforeEach, describe, expect, it, vi } from "vitest";
import { expectExecutionProvenance, useExecutionProvenanceFixture } from "./test_execution_provenance.js";

useExecutionProvenanceFixture();

const createRepositoryAdvisory = vi.fn();
const main = require("./create_security_advisory.cjs").main;
const tokenConfig = { "github-token": "external-token" };
const advisory = {
  summary: "Unsafe input handling",
  description: "Untrusted input can bypass validation in the affected package.",
  severity: "high",
  cwe_ids: ["CWE-20"],
  vulnerabilities: [{ package: { ecosystem: "npm", name: "example" }, vulnerable_version_range: "< 1.0.0", patched_versions: "1.0.0" }],
};
const created = { state: "draft", ghsa_id: "GHSA-2345-6789-cfgh", html_url: "https://github.com/test-owner/test-repo/security/advisories/GHSA-2345-6789-cfgh" };

describe("create_security_advisory", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    global.core = { info: vi.fn(), warning: vi.fn(), error: vi.fn(), setFailed: vi.fn(), summary: { addRaw: vi.fn().mockReturnThis(), write: vi.fn().mockResolvedValue(undefined) } };
    global.context = { repo: { owner: "test-owner", repo: "test-repo" }, payload: {}, runId: 12345 };
    vi.stubEnv("GH_AW_DETECTION_CONCLUSION", "");
    global.github = { rest: { securityAdvisories: { createRepositoryAdvisory } } };
    global.getOctokit = vi.fn(() => global.github);
    createRepositoryAdvisory.mockResolvedValue({ data: created });
  });

  it("uses the external token and returns the canonical draft URL", async () => {
    const handler = await main(tokenConfig);
    expect(await handler(advisory)).toEqual({ success: true, ghsa_id: created.ghsa_id, url: created.html_url });
    expect(global.getOctokit).toHaveBeenCalledWith("external-token", expect.any(Object));
    expect(createRepositoryAdvisory).toHaveBeenCalledWith({ ...global.context.repo, ...advisory, description: expect.stringContaining(advisory.description), start_private_fork: false });
    const body = createRepositoryAdvisory.mock.calls[0][0].description;
    expect(body).toContain("> Generated by");
    expectExecutionProvenance(body);
  });

  it("never forwards agent-supplied publication, fork, or repository controls", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...advisory, type: "create_security_advisory", state: "published", start_private_fork: true, private_fork: true, owner: "other", repo: "public-repo" });
    expect(createRepositoryAdvisory).toHaveBeenCalledWith({ ...global.context.repo, ...advisory, description: expect.stringContaining(advisory.description), start_private_fork: false });
  });

  it("rejects missing credentials rather than using the ambient Actions client", async () => {
    await expect(main()).rejects.toThrow("requires an external github-token or GitHub App token");
    await expect(main({ "github-token": " " })).rejects.toThrow("requires an external");
    expect(createRepositoryAdvisory).not.toHaveBeenCalled();
  });

  it("previews the complete prepared request in logs and step summary without authentication or API calls", async () => {
    const handler = await main({ staged: true });
    const input = { ...advisory, vulnerabilities: [{ ...advisory.vulnerabilities[0], vulnerable_functions: ["parseInput"] }] };
    expect(await handler(input)).toEqual({ success: true, staged: true });
    expect(global.getOctokit).not.toHaveBeenCalled();
    expect(createRepositoryAdvisory).not.toHaveBeenCalled();
    const preview = global.core.summary.addRaw.mock.calls[0][0];
    expect(preview).toContain("Staged Mode: Create Security Advisory Preview");
    const payload = JSON.parse(preview.match(/```json\n([\s\S]*?)\n```/)[1]);
    expect(payload).toEqual({ ...global.context.repo, ...input, description: expect.stringContaining(advisory.description), start_private_fork: false });
    expect(payload.description).toContain("> Generated by");
    expectExecutionProvenance(payload.description);
    expect(global.core.info).toHaveBeenCalledWith(preview);
    expect(global.core.summary.write).toHaveBeenCalledTimes(1);
    expect(global.core.setFailed).not.toHaveBeenCalled();
  });

  it.each(["private-advisory-preview-secret", 'private-"advisory\\preview-secret'])("redacts configured secret %j and credential patterns from every preview field", async secret => {
    const token = `ghp_${"a".repeat(36)}`;
    vi.stubEnv("GH_AW_SECRET_NAMES", "ADVISORY_PREVIEW");
    vi.stubEnv("SECRET_ADVISORY_PREVIEW", secret);
    const handler = await main({ staged: true, body_footer: `Policy ${secret}` });
    await handler({ ...advisory, summary: `${secret} ${token}`, description: `Details ${secret} ${token}`, vulnerabilities: [{ package: { ecosystem: "npm", name: secret }, vulnerable_functions: [token] }] });
    const output = JSON.stringify([global.core.info.mock.calls, global.core.summary.addRaw.mock.calls]);
    expect(output).not.toContain(secret);
    expect(output).not.toContain(token);
    const preview = global.core.summary.addRaw.mock.calls[0][0];
    const payload = JSON.parse(preview.match(/```json\n([\s\S]*?)\n```/)[1]);
    expect(payload.summary).not.toContain(secret);
    expect(payload.vulnerabilities[0].package.name).toBe("***");
    expect(payload.vulnerabilities[0].vulnerable_functions[0]).not.toContain(token);
    expect(output).toContain("***");
  });

  it("enforces max without creating another advisory", async () => {
    const handler = await main(tokenConfig);
    await handler(advisory);
    vi.stubEnv("GITHUB_REPOSITORY_ID", undefined);
    expect(await handler(advisory)).toMatchObject({ success: false, skipped: true, reasonCode: "MAX_COUNT_REACHED" });
    expect(createRepositoryAdvisory).toHaveBeenCalledTimes(1);
  });

  it.each([-1, "-1"])("supports the standard unlimited max value %j from a runtime expression", async max => {
    const handler = await main({ ...tokenConfig, max });
    expect(await handler(advisory)).toMatchObject({ success: true });
    expect(await handler(advisory)).toMatchObject({ success: true });
    expect(createRepositoryAdvisory).toHaveBeenCalledTimes(2);
  });

  it.each([0, "0", -2, "invalid", 1.5])("rejects invalid resolved max %j without API calls", async max => {
    await expect(main({ ...tokenConfig, max })).rejects.toThrow("max must be a positive integer or -1");
    expect(createRepositoryAdvisory).not.toHaveBeenCalled();
  });

  it("preserves the advisory summary limit and fits the complete description with attribution and policy", async () => {
    const handler = await main({ ...tokenConfig, body_footer: "Maintainer review is required." });
    await handler({ ...advisory, summary: "x".repeat(1024), description: "x".repeat(65000) });
    expect(createRepositoryAdvisory.mock.calls[0][0].summary).toHaveLength(1024);
    const body = createRepositoryAdvisory.mock.calls[0][0].description;
    expect(body.length).toBeLessThanOrEqual(65000);
    expect(body).toContain("> Generated by");
    expect(body).toContain("Maintainer review is required.");
    expectExecutionProvenance(body);
  });

  it.each([
    ["warning", "threat_detected", "gh-aw-threat-detected"],
    ["failure", "agent_failure", "gh-aw-threat-engine-error"],
    ["failure", "parse_error", "gh-aw-threat-engine-error"],
  ])("preserves warn-mode %s/%s notices and metadata when fitting the description", async (conclusion, reason, marker) => {
    vi.stubEnv("GH_AW_PROMPTS_DIR", new URL("../md/", import.meta.url).pathname);
    vi.stubEnv("GH_AW_DETECTION_CONCLUSION", conclusion);
    vi.stubEnv("GH_AW_DETECTION_REASON", reason);
    const handler = await main({ ...tokenConfig, footer: false, body_footer: "Required review policy." });
    await handler({ ...advisory, description: "x".repeat(65000) });
    const body = createRepositoryAdvisory.mock.calls[0][0].description;
    expect(body.length).toBeLessThanOrEqual(65000);
    expect(body).toContain(reason === "threat_detected" ? "[!CAUTION]" : "[!WARNING]");
    expect(body).toContain(`<!-- ${marker} -->`);
    expect(body).toContain("Required review policy.");
    expect(body).not.toContain("> Generated by");
    expectExecutionProvenance(body);
  });

  it("keeps attribution outside agent-controlled code fences", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...advisory, description: "```text\nunclosed agent content" });
    expect(createRepositoryAdvisory.mock.calls[0][0].description).toMatch(/unclosed agent content\n```\n[\s\S]*> Generated by/);
  });

  it.each([
    { summary: " " },
    { summary: "x".repeat(1025) },
    { description: "" },
    { description: "x".repeat(65001) },
    { vulnerabilities: [] },
    { vulnerabilities: [{ package: { ecosystem: "invalid" } }] },
    { vulnerabilities: [{ package: { ecosystem: "npm", name: "x".repeat(1025) } }] },
    { vulnerabilities: [{ package: { ecosystem: "npm", state: "published" } }] },
    { severity: "urgent" },
    { cwe_ids: ["invalid"] },
  ])("rejects invalid advisory data before API calls: %j", async fields => {
    const handler = await main(tokenConfig);
    await expect(handler({ ...advisory, ...fields })).rejects.toThrow("create_security_advisory");
    expect(createRepositoryAdvisory).not.toHaveBeenCalled();
  });

  it("sanitizes agent text before creating the advisory", async () => {
    const handler = await main(tokenConfig);
    await handler({ ...advisory, summary: "Unsafe\u0000 input", description: "Description\u0000 with invalid characters." });
    const payload = createRepositoryAdvisory.mock.calls[0][0];
    expect(payload.summary).not.toContain("\u0000");
    expect(payload.description).not.toContain("\u0000");
  });

  it("reports API errors without exposing confidential payloads or retrying", async () => {
    createRepositoryAdvisory.mockRejectedValueOnce(Object.assign(new Error(advisory.description), { status: 403 }));
    const handler = await main(tokenConfig);
    const result = await handler(advisory);
    expect(result).toMatchObject({ success: false, error: expect.stringContaining("HTTP 403") });
    expect(result.error).not.toContain(advisory.description);
    expect(await handler(advisory)).toMatchObject({ success: false, skipped: true, reasonCode: "MAX_COUNT_REACHED" });
    expect(createRepositoryAdvisory).toHaveBeenCalledTimes(1);
  });

  it("does not report success for a response that is not a draft", async () => {
    createRepositoryAdvisory.mockResolvedValueOnce({ data: { ...created, state: "published" } });
    const handler = await main(tokenConfig);
    expect(await handler(advisory)).toMatchObject({ success: false });
  });
});
