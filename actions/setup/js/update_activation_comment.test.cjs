const createTestableFunction = scriptContent => {
  const beforeMainCall = scriptContent.match(/^([\s\S]*?)\s*module\.exports\s*=\s*{[\s\S]*?};?\s*$/);
  if (!beforeMainCall) throw new Error("Could not extract script content before module.exports");
  let scriptBody = beforeMainCall[1];
  // Mock the error_helpers and messages_core modules
  const mockRequire = (module, threatDetectionWarning, actualRequire) => {
    if (["./report_markdown.cjs", "./report_size.cjs", "./messages_run_status.cjs", "./messages_footer.cjs"].includes(module)) return actualRequire(module);
    if (module === "./error_helpers.cjs") {
      return { getErrorMessage: error => (error instanceof Error ? error.message : String(error)) };
    }
    if (module === "./messages_core.cjs") {
      return {
        getMessages: () => {
          // Return messages config from environment
          const messagesEnv = process.env.GH_AW_SAFE_OUTPUT_MESSAGES;
          if (!messagesEnv) return null;
          try {
            return JSON.parse(messagesEnv);
          } catch (e) {
            return null;
          }
        },
      };
    }
    if (module === "./sanitize_content.cjs") {
      // Mock sanitizeContent to return input as-is for testing
      return { sanitizeContent: content => content };
    }
    if (module === "./messages_run_status.cjs") {
      const messagesEnv = process.env.GH_AW_SAFE_OUTPUT_MESSAGES;
      const messages = messagesEnv ? JSON.parse(messagesEnv) : null;
      const renderTmpl = (tmpl, ctx) => tmpl.replace(/\{(\w+)\}/g, (m, k) => (ctx[k] !== undefined ? String(ctx[k]) : m));
      const toSnake = obj => {
        const r = {};
        for (const [k, v] of Object.entries(obj)) {
          r[k.replace(/([A-Z])/g, "_$1").toLowerCase()] = v;
          r[k] = v;
        }
        return r;
      };
      return {
        getPullRequestCreatedMessage: ctx => {
          const tc = toSnake(ctx);
          const def = "Pull request created: [#{item_number}]({item_url})";
          return messages?.pullRequestCreated ? renderTmpl(messages.pullRequestCreated, tc) : renderTmpl(def, tc);
        },
        getIssueCreatedMessage: ctx => {
          const tc = toSnake(ctx);
          const def = "Issue created: [#{item_number}]({item_url})";
          return messages?.issueCreated ? renderTmpl(messages.issueCreated, tc) : renderTmpl(def, tc);
        },
        getCommitPushedMessage: ctx => {
          const tc = toSnake(ctx);
          const def = "Commit pushed: [`{short_sha}`]({commit_url})";
          return messages?.commitPushed ? renderTmpl(messages.commitPushed, tc) : renderTmpl(def, tc);
        },
        getDetectionWarningMessage: ctx => {
          const reasonText = threatDetectionWarning.getDetectionReasonText(ctx.reason);
          const warning = threatDetectionWarning.getThreatWarningPresentation(ctx.reason);
          return `> [!${warning.admonition}]\n> ${warning.title}\n> ${warning.summary}\n> ${warning.marker}\n>\n> ${reasonText}`;
        },
      };
    }
    if (module === "./templatable.cjs") {
      return {
        parseBoolTemplatable: (value, defaultValue = true) => {
          if (value === undefined || value === null) return defaultValue;
          return String(value) !== "false";
        },
      };
    }
    if (module === "./generate_footer.cjs") {
      return {
        generateXMLMarker: (workflowName, runUrl) => `<!-- gh-aw-agentic-workflow: ${workflowName}, run: ${runUrl} -->`,
      };
    }
    if (module === "./messages_footer.cjs") {
      return {
        getFooterMessage: ctx => `> Generated by [${ctx.workflowName}](${ctx.runUrl})`,
        getDetectionCautionAlert: (workflowName, runUrl) => {
          const conclusion = process.env.GH_AW_DETECTION_CONCLUSION;
          if (conclusion !== "warning") return "";
          const reason = process.env.GH_AW_DETECTION_REASON || "";
          return mockRequire("./messages_run_status.cjs", threatDetectionWarning).getDetectionWarningMessage({ workflowName, runUrl, reason });
        },
      };
    }
    if (module === "./threat_detection_warning.cjs") {
      return threatDetectionWarning;
    }
    if (module === "./workflow_metadata_helpers.cjs") {
      return {
        buildWorkflowRunUrl: (ctx, repo) => {
          const server = ctx.serverUrl || "https://github.com";
          return `${server}/${repo.owner}/${repo.repo}/actions/runs/${ctx.runId}`;
        },
      };
    }
    if (module === "./github_api_helpers.cjs") {
      return {
        resolveTopLevelDiscussionCommentId: async (githubClient, commentNodeId) => {
          // In tests, simulate that the triggering comment is always a top-level comment
          return commentNodeId;
        },
      };
    }
    if (module === "./invocation_context_helpers.cjs") {
      return {
        resolveInvocationContext: ctx => {
          if (ctx?.eventName === "repository_dispatch" && ctx?.payload?.client_payload) {
            const payload = ctx.payload.client_payload;
            const eventRepo = payload?.repository?.owner?.login && payload?.repository?.name ? { owner: payload.repository.owner.login, repo: payload.repository.name } : ctx.eventRepo || ctx.repo;
            return {
              source: "repository_dispatch",
              eventName: ctx.payload.action || ctx.eventName,
              eventPayload: payload,
              workflowRepo: ctx.workflowRepo || ctx.repo,
              eventRepo,
            };
          }

          if (ctx?.eventName === "workflow_dispatch" && ctx?.payload?.inputs) {
            const inputs = ctx.payload.inputs;
            let parsedPayload = ctx.payload;
            if (typeof inputs.event_payload === "string" && inputs.event_payload) {
              try {
                parsedPayload = JSON.parse(inputs.event_payload);
              } catch (_error) {
                parsedPayload = ctx.payload;
              }
            }
            const eventRepo =
              typeof inputs.event_repo === "string" && inputs.event_repo.includes("/")
                ? (() => {
                    const [owner, repo] = inputs.event_repo.split("/");
                    return { owner, repo };
                  })()
                : ctx.eventRepo || ctx.repo;
            return {
              source: "workflow_dispatch",
              eventName: inputs.event_name || ctx.eventName,
              eventPayload: parsedPayload,
              workflowRepo: ctx.workflowRepo || ctx.repo,
              eventRepo,
            };
          }

          return {
            source: "native",
            eventName: ctx?.eventName || "",
            eventPayload: ctx?.payload || {},
            workflowRepo: ctx?.workflowRepo || ctx?.repo,
            eventRepo: ctx?.eventRepo || ctx?.repo,
          };
        },
      };
    }
    throw new Error(`Module ${module} not mocked in test`);
  };
  const run = new Function(
    `\n    const { github, core, context, process, threatDetectionWarning } = arguments[0];\n    const actualRequire = arguments[1];\n    const mockRequire = ${mockRequire.toString()};\n    const require = module => mockRequire(module, threatDetectionWarning, actualRequire);\n    \n    ${scriptBody}\n    \n    return { updateActivationComment, updateActivationCommentWithCommit, updateActivationCommentWithMessage };\n  `
  );
  return options => run(options, createRequire(import.meta.url));
};
