// Package main generates Go data for embedded connector declarations.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var connectorIDPattern = regexp.MustCompile(`^[a-z][a-z0-9-]{0,62}$`)

func main() {
	root, err := findRepositoryRoot()
	if err != nil {
		fail(err)
	}

	sourceDir := filepath.Join(root, ".github", "workflows", "connectors")
	entries, err := os.ReadDir(sourceDir)
	if err != nil {
		fail(err)
	}

	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage workflow\n\n")
	output.WriteString("var builtinConnectorSources = map[string][]byte{\n")
	connectorCount := 0
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".md" {
			continue
		}
		id := strings.TrimSuffix(entry.Name(), ".md")
		if !connectorIDPattern.MatchString(id) {
			fail(fmt.Errorf("invalid built-in connector name %q", id))
		}
		content, err := os.ReadFile(filepath.Join(sourceDir, entry.Name()))
		if err != nil {
			fail(err)
		}
		if _, err := fmt.Fprintf(&output, "\t%q: []byte(%s),\n", id, strconv.Quote(string(content))); err != nil {
			fail(err)
		}
		connectorCount++
	}
	if connectorCount == 0 {
		fail(fmt.Errorf("no connector declarations found in %s", sourceDir))
	}
	output.WriteString("}\n")

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		fail(err)
	}
	outputPath := filepath.Join(root, "pkg", "workflow", "builtin_connector_data_generated.go")
	if err := os.WriteFile(outputPath, formatted, 0644); err != nil {
		fail(err)
	}
}

func findRepositoryRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			if _, err := os.Stat(filepath.Join(dir, ".github", "workflows", "connectors")); err == nil {
				return dir, nil
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("could not locate repository root")
		}
		dir = parent
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
