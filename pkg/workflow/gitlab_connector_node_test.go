func gitLabNodeAssets(t *testing.T) (string, string) {
	t.Helper()
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("Node.js is required to exercise the bundled GitLab connector host")
	}
	assets, err := filepath.Abs("../../actions/setup/js")
	require.NoError(t, err)
	return node, assets
}

//nolint:misspell // GitLab's JSON wire fields use noteable, not notable.
func TestGitLabConnectorBundledNodeStagingAndReads(t *testing.T) {
	node, assets := gitLabNodeAssets(t)
	source := strings.NewReplacer(
		`projects: ["42"]`, `projects: ["42", "43"]`,
		`merge-requests: ["7"]`, `merge-requests: ["7", "8"]`,
		`pipelines: ["900"]`, `pipelines: ["900", "901"]`,
	).Replace(gitLabConsumerSource(t,
		"tools:\n  gitlab: [get-merge-request, get-pipeline]\nsafe-outputs:\n  gitlab-add-merge-request-note:\n"))
	_, data, _, err := parseGitLabConsumer(t, source)
	require.NoError(t, err)
	agent, err := data.Connectors["gitlab"].Agent.Encode()
	require.NoError(t, err)
	writer, err := data.Connectors["gitlab"].SafeOutputs.Encode()
	require.NoError(t, err)
	input, err := json.Marshal(map[string]any{
		"agent": agent, "writer": writer, "mr": gitLabResponseFixture(t, "merge-request"),
		"pipeline": gitLabResponseFixture(t, "pipeline"), "note": gitLabResponseFixture(t, "note"),
	})
	require.NoError(t, err)
	command := exec.CommandContext(t.Context(), node, "-e", `
const assert = require("node:assert/strict");
const { Readable, Writable } = require("node:stream");
const { executeConnector, serve } = require(process.argv[1]);
const input = JSON.parse(require("node:fs").readFileSync(0, "utf8"));
const noteArgs = { project: "42", "merge-request": "7", body: "Coordination review requested." };
let blockedSecretReads = 0, blockedNetworkCalls = 0;
const blockedEnv = new Proxy({}, { get() { blockedSecretReads++; throw new Error("Staging accessed a secret"); } });
const noNetwork = () => { blockedNetworkCalls++; throw new Error("Staging accessed the network"); };
const staged = { staged: true, env: blockedEnv, fetchImpl: noNetwork };
(async () => {
  const intent = await executeConnector(input.writer, "safe-output", "add-merge-request-note", noteArgs, staged);
  assert.equal(intent.staged, true);
  assert.deepEqual(intent.request.arguments, noteArgs);
  await executeConnector(input.writer, "safe-output", "add-merge-request-note", {...noteArgs, body: "A".repeat(2000)}, staged);
  for (const body of ["", "A".repeat(2001), "/merge", "Text\n/close", "Text\r/close", "Text\r\n/close",
    "Text\r", "Text\n /close", "Text\n\t/merge", "Text\n   /label", "Text\r\n /close", "Text\r\n\t/merge"]) {
    await assert.rejects(() => executeConnector(input.writer, "safe-output", "add-merge-request-note", {...noteArgs, body}, staged));
  }
  await executeConnector(input.writer, "safe-output", "add-merge-request-note", {...noteArgs,
    body: "Coordination note.\n\n> Generated by [Workflow](https://github.com/example/repo/actions/runs/42)\n\n<!-- gh-aw-agentic-workflow: Workflow -->"}, staged);
  for (const args of [
    {...noteArgs, project: "44"}, {...noteArgs, "merge-request": "9"},
    {...noteArgs, "merge-request": 7}, {...noteArgs, "merge-request": "07"},
    {...noteArgs, "merge-request": "7\n"}, {...noteArgs, "merge-request": "7/notes"},
    {...noteArgs, internal: true}, {...noteArgs, url: "https://other.invalid"}
  ]) await assert.rejects(() => executeConnector(input.writer, "safe-output", "add-merge-request-note", args, staged));
  assert.equal(blockedSecretReads, 0);
  assert.equal(blockedNetworkCalls, 0);

  let calls = 0;
  const env = {
    GH_AW_CONNECTOR_SECRET_APPROVED_GITLAB_READER: "fixture-reader",
    GH_AW_CONNECTOR_SECRET_APPROVED_GITLAB_WRITER: "fixture-writer"
  };
  const fetchImpl = async (url, options) => {
    calls++;
    assert.equal(options.redirect, "manual");
    const target = new URL(url);
    assert.equal(target.origin, "https://gitlab.com");
    assert.equal(target.search, "");
    assert.equal(new Headers(options.headers).get("Authorization"), null);
    const write = options.method === "POST";
    assert.equal(new Headers(options.headers).get("PRIVATE-TOKEN"), write ? "fixture-writer" : "fixture-reader");
    if (write) {
      assert.equal(target.pathname, "/api/v4/projects/42/merge_requests/7/notes");
      assert.deepEqual(JSON.parse(options.body), {body: noteArgs.body});
    }
    return new Response(write ? input.note : target.pathname.endsWith("/900") ? input.pipeline : input.mr);
  };
  const readMR = await executeConnector(input.agent, "mcp", "get-merge-request", {project:"42", "merge-request":"7"}, {env, fetchImpl});
  assert.equal(readMR.untrusted, true);
  assert.deepEqual(Object.keys(readMR.data).sort(), ["draft", "id", "merge-request", "project", "state", "title"]);
  const readPipeline = await executeConnector(input.agent, "mcp", "get-pipeline", {project:"42", pipeline:"900"}, {env, fetchImpl});
  assert.deepEqual(Object.keys(readPipeline.data).sort(), ["pipeline", "project", "ref", "sha", "source", "status"]);
  const note = await executeConnector(input.writer, "safe-output", "add-merge-request-note", noteArgs, {env, fetchImpl});
  assert.deepEqual(JSON.parse(JSON.stringify(note.data)), {note:301, project:42, "merge-request":7});
  assert.equal(calls, 3);
  await assert.rejects(() => executeConnector(input.agent, "mcp", "get-pipeline", {project:"42",pipeline:"900"}, {env:{}, fetchImpl:noNetwork}));
  await assert.rejects(() => executeConnector(input.writer, "safe-output", "add-merge-request-note", noteArgs, {env:{}, fetchImpl:noNetwork}));
  assert.equal(blockedNetworkCalls, 0);

  for (const operation of [
    {plan:input.agent, capability:"mcp", name:"get-merge-request", args:{project:"42","merge-request":"7"}, body:input.mr},
    {plan:input.agent, capability:"mcp", name:"get-pipeline", args:{project:"42",pipeline:"900"}, body:input.pipeline},
    {plan:input.writer, capability:"safe-output", name:"add-merge-request-note", args:noteArgs, body:input.note}
  ]) {
    for (const status of [301, 401, 403, 404, 429, 503]) {
      let attempts = 0;
      await assert.rejects(() => executeConnector(operation.plan, operation.capability, operation.name, operation.args, {
        env, fetchImpl: async () => { attempts++; return new Response("denied", {status, headers:{"Location":"https://other.invalid", "Retry-After":"1"}}); }
      }));
      assert.equal(attempts, 1);
    }
    for (const body of [
      operation.body.replace('"project_id": 42', '"project_id": 43'),
      operation.body.replace('"project_id": 42', '"project_id": "42"'),
      operation.body.replace('"iid": 7', '"iid": 8').replace('"id": 900', '"id": 901').replace('"noteable_iid": 7', '"noteable_iid": 8'),
      "not JSON", "{}", "x".repeat(65537)
    ]) {
      let attempts = 0;
      await assert.rejects(() => executeConnector(operation.plan, operation.capability, operation.name, operation.args, {
        env, fetchImpl: async () => { attempts++; return new Response(body); }
      }));
      assert.equal(attempts, 1);
    }
  }

  const messages = [
    {id:1, method:"tools/list"},
    {id:2, method:"tools/call", params:{name:"gitlab_get_pipeline", arguments:{project:"42",pipeline:"900"}}},
    {id:3, method:"tools/call", params:{name:"connector_6_gitlab_get_pipeline", arguments:{project:"42",pipeline:"900"}}}
  ].map(message => JSON.stringify({jsonrpc:"2.0", ...message}) + "\n");
  let output = "";
  await serve(input.agent, Readable.from(messages), new Writable({write(chunk, encoding, done) { output += chunk; done(); }}), {env, fetchImpl});
  const responses = output.trim().split("\n").map(line => JSON.parse(line));
  assert.deepEqual(responses[0].result.tools.map(tool => tool.name), ["gitlab_get_merge_request", "gitlab_get_pipeline"]);
  assert.equal(responses[1].result.isError, undefined);
  assert.equal(JSON.parse(responses[1].result.content[0].text).untrusted, true);
  assert.equal(responses[2].result.isError, true);
  assert.equal(calls, 4);
  process.stdout.write("GitLab Node staging, scope, reads, effects, and MCP boundaries passed");
})().catch(error => { console.error(error); process.exitCode = 1; });
`, filepath.Join(assets, "connector_runtime.cjs"))
	command.Stdin = strings.NewReader(string(input))
	output, err := command.CombinedOutput()
	require.NoError(t, err, "%s", output)
	require.Contains(t, string(output), "boundaries passed")
}

func TestGitLabConnectorGeneratedNodeHostStagesWithoutSecretsOrNetwork(t *testing.T) {
	node, assets := gitLabNodeAssets(t)
	root := t.TempDir()
	target := filepath.Join(root, "gh-aw", "actions")
	require.NoError(t, os.MkdirAll(target, 0700))
	for _, file := range []string{"connector_runtime.cjs", "connector_regex.cjs", "error_codes.cjs"} {
		content, err := os.ReadFile(filepath.Join(assets, file))
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(target, file), content, 0600))
	}
	for _, mode := range []string{"authored-staged", "forced-staged"} {
		t.Run(mode, func(t *testing.T) {
			selection := "safe-outputs:\n  gitlab-add-merge-request-note:\n"
			if mode == "authored-staged" {
				selection = "safe-outputs:\n  staged: true\n  gitlab-add-merge-request-note:\n"
			}
			compiler, data, path, err := parseGitLabConsumer(t, gitLabConsumerSource(t, selection))
			require.NoError(t, err)
			if mode == "forced-staged" {
				compiler.forceStaged = true
				data, err = compiler.ParseWorkflowFile(path)
				require.NoError(t, err)
			}
			lock, err := compiler.CompileToYAML(data, path)
			require.NoError(t, err)
			require.Contains(t, lock, "gitlab_add_merge_request_note")
			require.NotContains(t, lock, "${{ secrets.APPROVED_GITLAB_WRITER }}")
			for _, obsolete := range []string{"connector_6_gitlab", "Checkout trusted connector runtime", "Build trusted connector runtime", ".gh-aw-connector-runtime"} {
				require.NotContains(t, lock, obsolete)
			}
			script := data.SafeOutputs.Scripts["gitlab-add-merge-request-note"]
			require.NotNil(t, script)
			configuration, err := json.Marshal(map[string]any{
				"script": script.Script, "root": root, "assets": assets, "authored": mode == "authored-staged",
				"secret":  connectorCredentialEnvPrefix("gitlab") + "APPROVED_GITLAB_WRITER",
				"planEnv": connectorEnvPrefix("gitlab") + "PLAN", "plan": data.Connectors["gitlab"].SafeOutputPlan,
			})
			require.NoError(t, err)
			command := exec.CommandContext(t.Context(), node, "-e", `
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const childProcess = require("node:child_process");
const config = JSON.parse(fs.readFileSync(0, "utf8"));
const args = {project:"42", "merge-request":"7", body:"Coordination review requested."};
process.env.GH_AW_SAFE_OUTPUTS_STAGED = String(config.authored);
const guard = path.join(config.root, "no-network-or-secret.cjs");
fs.writeFileSync(guard, [
  "globalThis.fetch = () => { throw new Error('Unexpected network request'); };",
  "process.env = new Proxy(process.env, { get(target, name) {",
  "  if (String(name).startsWith('GH_AW_CONNECTOR_SECRET_')) throw new Error('Unexpected secret access');",
  "  return target[name];",
  "} });"
].join("\n"));
const env = {RUNNER_TEMP:config.root, [config.planEnv]:config.plan};
Object.defineProperty(env, config.secret, {get() { throw new Error("Generated host accessed writer secret"); }});
let calls = 0, formatted;
const adaptedRequire = name => {
  if (name.startsWith("./")) return require(path.join(config.assets, name));
  if (name === "node:child_process") return {spawnSync(binary, arguments_, options) {
    calls++;
    assert.equal(binary, process.execPath);
    assert.deepEqual(arguments_, [path.join(config.root, "gh-aw", "actions", "connector_runtime.cjs"), "invoke", "safe-output", "add-merge-request-note", "--stage"]);
    assert.deepEqual(Object.keys(options.env), ["GH_AW_CONNECTOR_PLAN"]);
    const { decodePlan } = require(path.join(config.assets, "connector_runtime.cjs"));
    const { formatConnectorArguments } = require(path.join(config.assets, "connector_content.cjs"));
    formatted = formatConnectorArguments(decodePlan(options.env.GH_AW_CONNECTOR_PLAN), "add-merge-request-note", args);
    assert.deepEqual(JSON.parse(options.input), formatted);
    return childProcess.spawnSync(binary, ["--require", guard, ...arguments_], options);
  }};
  return require(name);
};
const result = new Function("item", "require", "process", "temporaryIdMap", config.script)(
  {type:"gitlab_add_merge_request_note", ...args}, adaptedRequire, {env, execPath:process.execPath}, new Map()
);
assert.equal(calls, 1);
assert.equal(result.staged, true);
assert.deepEqual(result.request.arguments, formatted);
assert.equal(result.request.operation, "add-merge-request-note");
process.stdout.write("Generated GitLab Node host staged without credentials or network");
`)
			command.Stdin = strings.NewReader(string(configuration))
			command.Env = []string{}
			output, err := command.CombinedOutput()
			require.NoError(t, err, "%s", output)
			require.Contains(t, string(output), "without credentials or network")
		})
	}
}
