func steeringTestData() *WorkflowData {
	return &WorkflowData{
		Name:            "Steering test",
		MarkdownContent: "# Test",
		SafeOutputs: &SafeOutputsConfig{
			Steer: true,
		},
	}
}

func TestBuildActivationJobCreatesSteeringIssue(t *testing.T) {
	compiler := NewCompiler()
	data := steeringTestData()
	data.SafeOutputs.CreatePullRequests = &CreatePullRequestsConfig{}
	job, err := compiler.buildActivationJob(data, false, "", "test.lock.yml")
	require.NoError(t, err)

	steps := strings.Join(job.Steps, "")
	assert.Contains(t, steps, "id: create-steering-issue")
	assert.Contains(t, steps, "if: steps.daily-ai-credits-workflow-guardrail.outputs.daily_ai_credits_exceeded != 'true' && steps.daily-ai-credits-workflow-guardrail.outputs.daily_ai_credits_guardrail_status != 'quota_blocked'")
	assert.Contains(t, steps, "create_steering_issue.cjs")
	assert.Contains(t, job.Permissions, "issues: write")
	assert.NotContains(t, job.Permissions, "contents: write")
	assert.NotContains(t, job.Permissions, "pull-requests: write")
	assert.NotContains(t, job.Permissions, "checks: write")
	assert.Equal(t, "${{ steps.create-steering-issue.outputs.issue_number }}", job.Outputs["steering_issue_number"])
	assert.Equal(t, "${{ steps.create-steering-issue.outputs.issue_url }}", job.Outputs["steering_issue_url"])
	assert.Contains(t, steps, "GH_AW_NEEDS_ACTIVATION_OUTPUTS_STEERING_ISSUE_NUMBER: ${{ (steps.create-steering-issue.outputs.issue_number) }}")
	assert.NotContains(t, steps, "${{ needs.activation.outputs.steering_issue_number }}")
}

func TestBuildConclusionJobReusesAndCompletesSteeringIssue(t *testing.T) {
	compiler := NewCompiler()
	job, err := compiler.buildConclusionJob(steeringTestData(), "agent", []string{"safe_outputs"})
	require.NoError(t, err)
	require.NotNil(t, job)

	steps := strings.Join(job.Steps, "")
	assert.Contains(t, steps, "GH_AW_STEERING_ISSUE_NUMBER: ${{ needs.activation.outputs.steering_issue_number }}")
	assert.Contains(t, steps, "complete_steering_issue.cjs")
	assert.Contains(t, steps, "GH_AW_CREATED_PR_NUMBER: ${{ needs.safe_outputs.outputs.created_pr_number }}")
	assert.Contains(t, job.If, "needs.activation.outputs.steering_issue_number")
	assert.Contains(t, job.Permissions, "issues: write")
}

func TestActivationSteeringIssueWithoutDailyGuardrail(t *testing.T) {
	for _, name := range []string{"disabled", "dry-run"} {
		t.Run(name, func(t *testing.T) {
			data := steeringTestData()
			if name == "disabled" {
				data.RawFrontmatter = map[string]any{"max-daily-ai-credits": -1}
			} else {
				data.DryRun = true
			}
			ctx := &activationJobBuildContext{data: data, outputs: make(map[string]string)}
			NewCompiler().addActivationSteeringIssueStep(ctx)
			steps := strings.Join(ctx.steps, "")
			assert.Contains(t, steps, "id: create-steering-issue")
			assert.NotContains(t, steps, "daily-ai-credits-workflow-guardrail")
		})
	}
}

func TestBuildActivationSteeringIssueAttribution(t *testing.T) {
	data := steeringTestData()
	data.WorkflowID = "steering-test"
	data.TrackerID = "tracker-123"
	data.Source = "owner/repo/steering.md@main"
	data.EngineConfig = &EngineConfig{ID: "copilot", Version: "1.0.0"}
	data.SafeOutputs.Messages = &SafeOutputMessagesConfig{Footer: "> Generated by {workflow_name}"}

	compiler := NewCompiler()
	job, err := compiler.buildActivationJob(data, false, "", "test.lock.yml")
	require.NoError(t, err)

	steps := strings.Join(job.Steps, "")
	start := strings.Index(steps, "      - name: Create steering issue\n")
	require.NotEqual(t, -1, start)
	step := strings.SplitN(steps[start:], "\n      - ", 2)[0]
	assert.Contains(t, step, `GH_AW_WORKFLOW_NAME: "Steering test"`)
	assert.Contains(t, step, `GH_AW_WORKFLOW_ID: "steering-test"`)
	assert.Contains(t, step, `GH_AW_TRACKER_ID: "tracker-123"`)
	assert.Contains(t, step, `GH_AW_WORKFLOW_SOURCE: "owner/repo/steering.md@main"`)
	assert.Contains(t, step, `GH_AW_WORKFLOW_SOURCE_URL: "${{ github.server_url }}/owner/repo/blob/main/steering.md"`)
	assert.Contains(t, step, "GH_AW_ENGINE_ID: ${{ steps.generate_aw_info.outputs.engine_id }}")
	assert.Contains(t, step, "GH_AW_ENGINE_MODEL: ${{ steps.generate_aw_info.outputs.model }}")
	assert.Contains(t, step, `GH_AW_ENGINE_VERSION: "1.0.0"`)
	assert.Contains(t, step, "GH_AW_SAFE_OUTPUT_MESSAGES:")
	assert.NotContains(t, step, "needs.agent")
	assert.Less(t, strings.Index(steps, "id: generate_aw_info"), start)
}

