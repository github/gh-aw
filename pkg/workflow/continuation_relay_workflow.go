var continuationRelayWorkflowLog = logger.New("workflow:continuation_relay_workflow")

const continuationRelayWorkflowName = "Agentic Continuation Relay"

// ContinuationRelayEnabled reports whether any compiled workflow can request continuation.
func ContinuationRelayEnabled(workflowDataList []*WorkflowData) bool {
	return slices.ContainsFunc(workflowDataList, hasRequestContinuation)
}

// GenerateContinuationRelayWorkflow writes the generic continuation relay when at least one
// workflow enables safe-outputs.request-continuation, and removes it otherwise. The relay is
// the only component that dispatches continuation runs; it trusts only the parent's compiled
// lock-file metadata and continuation artifacts, never its dispatch inputs.
func GenerateContinuationRelayWorkflow(ctx context.Context, workflowDataList []*WorkflowData, workflowDir string, repoConfig *RepoConfig, noLogo ...bool) error {
	path := filepath.Join(workflowDir, ContinuationRelayWorkflowFile)
	if !ContinuationRelayEnabled(workflowDataList) {
		continuationRelayWorkflowLog.Print("No workflow requests continuation; removing generated relay")
		if err := removeIfExists(path); err != nil {
			return fmt.Errorf("failed to remove generated continuation relay workflow: %w", err)
		}
		return nil
	}

	var resolver SHAResolver
	for _, data := range workflowDataList {
		if data != nil && data.ActionResolver != nil {
			resolver = data.ActionResolver
			break
		}
	}
	actionMode := DetectActionMode(GetVersion())
	setupActionRef := ResolveSetupActionReference(ctx, actionMode, GetVersion(), "", resolver)
	content, err := buildContinuationRelayWorkflowYAML(actionMode, setupActionRef, resolver, shouldIncludeLockFileLogo(repoConfig, noLogo...))
	if err != nil {
		return err
	}
	if repoConfig != nil {
		content, err = mapPinnedUsesInYAML(content, repoConfig.ActionPins, repoConfig.ActionPinPrefixes, actionPinWarningsForWorkflows(workflowDataList), resolver)
		if err != nil {
			return fmt.Errorf("failed to apply configured action pins to continuation relay workflow: %w", err)
		}
	}
	if err := os.MkdirAll(workflowDir, constants.DirPermPublic); err != nil {
		return fmt.Errorf("failed to create workflow directory for continuation relay workflow: %w", err)
	}
	if err := os.WriteFile(path, []byte(content), constants.FilePermPublic); err != nil {
		return fmt.Errorf("failed to write continuation relay workflow: %w", err)
	}
	continuationRelayWorkflowLog.Printf("Generated continuation relay workflow: %s", path)
	return nil
}

func buildContinuationRelayWorkflowYAML(actionMode ActionMode, setupActionRef string, resolver SHAResolver, logo bool) (string, error) {
	var b strings.Builder
	b.WriteString(GenerateWorkflowHeader("", "pkg/workflow/continuation_relay_workflow.go", "This file is generated by gh-aw to relay safe-outputs.request-continuation runs.", logo))
	b.WriteString("name: " + continuationRelayWorkflowName + "\n")
	b.WriteString(`run-name: Continuation relay ${{ inputs.parent_run_id }}/${{ inputs.parent_run_attempt }}
concurrency:
  group: continuation-relay-${{ github.repository_id }}-${{ inputs.parent_run_id }}-${{ inputs.parent_run_attempt }}
  cancel-in-progress: false


on:
  workflow_dispatch:
    inputs:
      parent_run_id:
        description: "Run ID of the workflow run that requested continuation"
        required: true
        type: string
      parent_run_attempt:
        description: "Attempt that produced the continuation request"
        required: true
        type: string
      checkpoint_run_attempt:
        description: "Attempt that produced the durable checkpoint"
        required: true
        type: string

permissions: {}

jobs:
`)
	githubScript := getCachedActionPinFromResolver("actions/github-script", resolver)
	opts := buildMaintenanceWorkflowYAMLOptions{actionMode: actionMode}
	writeContinuationRelayResolveJob(&b, opts, setupActionRef, githubScript)
	writeContinuationRelayApproveAndDispatchJobs(&b, opts, setupActionRef, githubScript, resolver)

	finalized, err := finalizeRunnerTempSafety(b.String())
	if err != nil {
		return "", fmt.Errorf("failed to finalize continuation relay workflow: %w", err)
	}
	return documentPermissionComments(finalized, "")
}

func writeContinuationRelayResolveJob(b *strings.Builder, opts buildMaintenanceWorkflowYAMLOptions, setupActionRef, githubScript string) {
	b.WriteString(`  resolve:
    name: Validate continuation request
    if: ${{ github.event_name == 'workflow_dispatch' && !github.event.repository.fork && github.ref == format('refs/heads/{0}', github.event.repository.default_branch) }}
    runs-on: ubuntu-slim
    permissions:
      actions: read
      contents: read
    outputs:
      approval_environment: ${{ steps.resolve.outputs.approval_environment }}
      depth: ${{ steps.resolve.outputs.depth }}
      max: ${{ steps.resolve.outputs.max }}
      ref: ${{ steps.resolve.outputs.ref }}
      target_workflow: ${{ steps.resolve.outputs.target_workflow }}
    steps:
`)
	writeMaintenanceConditionalActionsCheckoutStep(b, opts)
	writeMaintenanceSetupScriptsStep(b, setupActionRef)
	writeContinuationRelayScriptStep(b, githubScript, "Validate continuation request", "resolve", "resolve", "")
}

func writeContinuationRelayApproveAndDispatchJobs(b *strings.Builder, opts buildMaintenanceWorkflowYAMLOptions, setupActionRef, githubScript string, resolver SHAResolver) {
	b.WriteString(`  approve:
    name: Approve continuation
    needs: resolve
    if: ${{ needs.resolve.outputs.approval_environment != '' }}
    runs-on: ubuntu-slim
    environment: ${{ needs.resolve.outputs.approval_environment }}
    permissions: {}
    steps:
      - name: Record approval
        env:
          GH_AW_TARGET_WORKFLOW: ${{ needs.resolve.outputs.target_workflow }}
          GH_AW_CONTINUATION_DEPTH: ${{ needs.resolve.outputs.depth }}
          GH_AW_CONTINUATION_MAX: ${{ needs.resolve.outputs.max }}
        run: echo "Continuation $GH_AW_CONTINUATION_DEPTH of $GH_AW_CONTINUATION_MAX for $GH_AW_TARGET_WORKFLOW approved"

  dispatch:
    name: Dispatch continuation run
    needs:
      - resolve
      - approve
    if: ${{ !cancelled() && needs.resolve.result == 'success' && (needs.approve.result == 'success' || (needs.approve.result == 'skipped' && needs.resolve.outputs.approval_environment == '')) }}
    runs-on: ubuntu-slim
    permissions:
      actions: write
      contents: read
    steps:
`)
	writeMaintenanceConditionalActionsCheckoutStep(b, opts)
	writeMaintenanceSetupScriptsStep(b, setupActionRef)
	writeContinuationRelayScriptStep(b, githubScript, "Dispatch continuation run", "dispatch", "dispatch",
		"          GH_AW_APPROVAL_RESULT: ${{ needs.approve.result }}\n"+
			"          GH_AW_APPROVAL_ENVIRONMENT: ${{ needs.resolve.outputs.approval_environment }}\n")
	b.WriteString(`      - name: Record dispatched continuation
        if: ${{ always() }}
        uses: ` + getCachedActionPinFromResolver("actions/upload-artifact", resolver) + `
        with:
          name: continuation-dispatched
          path: ${{ runner.temp }}/gh-aw/continuation-relay/dispatched.json
          if-no-files-found: ignore
          retention-days: 90
`)
}

func writeContinuationRelayScriptStep(b *strings.Builder, githubScript, name, id, entryPoint, extraEnv string) {
	b.WriteString(`      - name: ` + name + `
        id: ` + id + `
        uses: ` + githubScript + `
        env:
          GH_AW_PARENT_RUN_ID: ${{ inputs.parent_run_id }}
          GH_AW_PARENT_RUN_ATTEMPT: ${{ inputs.parent_run_attempt }}
          GH_AW_PARENT_CHECKPOINT_ATTEMPT: ${{ inputs.checkpoint_run_attempt }}
          GH_AW_RELAY_TOKEN: ${{ github.token }}
` + extraEnv + `        with:
          script: |
            const { setupGlobals } = require('${{ runner.temp }}/gh-aw/actions/setup_globals.cjs');
            setupGlobals(core, github, context, exec, io, getOctokit);
            const { ` + entryPoint + ` } = require('${{ runner.temp }}/gh-aw/actions/continuation_relay.cjs');
            await ` + entryPoint + `();

`)
}
