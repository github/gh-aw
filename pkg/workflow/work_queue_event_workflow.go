package workflow

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/github/gh-aw/pkg/constants"
	"github.com/github/gh-aw/pkg/logger"
)

var workQueueEventWorkflowLog = logger.New("workflow:work_queue_event_workflow")

const workQueueEventWorkflowFilename = "agentic-workqueue.yml"
const workQueueEventWorkflowName = "Agentic Workqueue"

// GenerateWorkQueueEventWorkflow generates trusted Issue lifecycle handlers.
func GenerateWorkQueueEventWorkflow(ctx context.Context, workflowDataList []*WorkflowData, workflowDir string, repoConfig *RepoConfig, noLogo ...bool) error {
	path := filepath.Join(workflowDir, workQueueEventWorkflowFilename)
	if !WorkQueueIssueMirroringEnabled(workflowDataList) {
		workQueueEventWorkflowLog.Print("No work queue events are used; removing generated workflow")
		if err := removeIfExists(path); err != nil {
			return fmt.Errorf("failed to remove generated work queue event workflow: %w", err)
		}
		return nil
	}

	var resolver SHAResolver
	for _, data := range workflowDataList {
		if data != nil && data.ActionResolver != nil {
			resolver = data.ActionResolver
			break
		}
	}
	actionMode := DetectActionMode(GetVersion())
	setupActionRef := ResolveSetupActionReference(ctx, actionMode, GetVersion(), "", resolver)
	content, err := buildWorkQueueEventWorkflowYAML(actionMode, setupActionRef, resolver, shouldIncludeLockFileLogo(repoConfig, noLogo...))
	if err != nil {
		return err
	}
	if repoConfig != nil {
		content, err = mapPinnedUsesInYAML(content, repoConfig.ActionPins, repoConfig.ActionPinPrefixes, actionPinWarningsForWorkflows(workflowDataList), resolver)
		if err != nil {
			return fmt.Errorf("failed to apply configured action pins to work queue event workflow: %w", err)
		}
	}
	if err := os.MkdirAll(workflowDir, constants.DirPermPublic); err != nil {
		return fmt.Errorf("failed to create workflow directory for work queue event workflow: %w", err)
	}
	if err := os.WriteFile(path, []byte(content), constants.FilePermPublic); err != nil {
		return fmt.Errorf("failed to write work queue event workflow: %w", err)
	}
	workQueueEventWorkflowLog.Printf("Generated work queue event workflow: %s", path)
	return nil
}

func buildWorkQueueEventWorkflowYAML(actionMode ActionMode, setupActionRef string, resolver SHAResolver, logo bool) (string, error) {
	var b strings.Builder
	b.WriteString(GenerateWorkflowHeader("", "pkg/workflow/work_queue_event_workflow.go", "This file is generated by gh-aw for work queue events.", logo))
	b.WriteString("name: " + workQueueEventWorkflowName + "\n\non:\n")
	b.WriteString(`  issues:
    types: [closed]
  issue_comment:
    types: [created]

permissions: {}

jobs:
`)
	writeWorkQueueIssueEventsJob(&b, actionMode, setupActionRef, resolver)
	finalized, err := finalizeRunnerTempSafety(b.String())
	if err != nil {
		return "", fmt.Errorf("failed to finalize work queue event workflow: %w", err)
	}
	return documentPermissionComments(finalized, "")
}

func writeWorkQueueIssueEventsJob(b *strings.Builder, actionMode ActionMode, setupActionRef string, resolver SHAResolver) {
	b.WriteString(`  issue_events:
    if: ${{ github.event.issue.pull_request == null && !(github.event.repository.fork) }}
    name: Handle work queue Issue events
    runs-on: ubuntu-slim
    permissions:
      actions: read
      contents: write
      issues: write
    steps:
`)
	writeMaintenanceConditionalActionsCheckoutStep(b, buildMaintenanceWorkflowYAMLOptions{actionMode: actionMode})
	writeMaintenanceSetupScriptsStep(b, setupActionRef)
	b.WriteString(`      - name: Process work queue Issue event
        uses: ` + getCachedActionPinFromResolver("actions/github-script", resolver) + `
        with:
          script: |
            const { setupGlobals } = require('${{ runner.temp }}/gh-aw/actions/setup_globals.cjs');
            setupGlobals(core, github, context, exec, io, getOctokit);
            const { main } = require('${{ runner.temp }}/gh-aw/actions/cancel_work_queue_closed_issue.cjs');
            await main();
`)
}
