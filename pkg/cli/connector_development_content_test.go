func TestConnectorDevelopmentPublicationFencesAndSingleFormatting(t *testing.T) {
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node.js is required for shared publication conformance")
	}
	t.Setenv("GH_AW_CLI_SYNTHETIC_PARENT_SECRET", "synthetic-only")
	t.Setenv("GITHUB_REPOSITORY", "synthetic/parent")
	t.Setenv("GITHUB_RUN_ID", "9999")
	root := t.TempDir()
	actualRuntime, err := filepath.Abs("../../actions/setup/js/connector_runtime.cjs")
	require.NoError(t, err)
	actualContent, err := filepath.Abs("../../actions/setup/js/connector_content.cjs")
	require.NoError(t, err)
	runtimeJSON, err := json.Marshal(actualRuntime)
	require.NoError(t, err)
	contentJSON, err := json.Marshal(actualContent)
	require.NoError(t, err)
	runtimePath := filepath.Join(root, "connector_runtime.cjs")
	require.NoError(t, os.WriteFile(runtimePath, []byte(`
const assert = require("node:assert/strict");
const runtime = require(`+string(runtimeJSON)+`);
module.exports = {
  ...runtime,
  async executeConnector(encoded, capability, name, args, options) {
    assert.throws(() => options.env.DEV_WRITE_TOKEN, /forbids/);
    await assert.rejects(options.fetchImpl(), /forbids/);
    await assert.rejects(global.fetch(), /forbids/);
    return runtime.executeConnector(encoded, capability, name, args, options);
  },
};`), 0600))
	require.NoError(t, os.WriteFile(filepath.Join(root, "connector_content.cjs"), []byte(`
const assert = require("node:assert/strict");
assert.equal(typeof global.core.info, "function", "install the core logger before requiring the helper");
global.core.info("synthetic-body diagnostic");
assert.equal(process.env.GH_AW_CLI_SYNTHETIC_PARENT_SECRET, undefined);
assert.equal(process.env.GITHUB_REPOSITORY, undefined);
assert.equal(process.env.GITHUB_RUN_ID, undefined);
const helper = require(`+string(contentJSON)+`);
let calls = 0;
module.exports = {
  formatConnectorArguments(...args) {
    assert.equal(++calls, 1, "publication content must be formatted only once");
    return helper.formatConnectorArguments(...args);
  },
};`), 0600))
	declaration := loadDevelopmentConnector(t, developmentPublicationFixture(), map[string][]string{"issues": {"ISSUE-1"}})
	options := developmentOptions("safe-output", "add-note", `{"issue":"ISSUE-1","heading":"An actual publication title","text":"Local prose @everyone {{ template }}"}`)
	options.timeout = 20 * time.Second
	options.nodeRuntime = runtimePath
	var output bytes.Buffer
	require.NoError(t, testDevelopmentConnector(t.Context(), &output, declaration, options, nil, nil))
	require.Contains(t, output.String(), "Default shared publication formatting passed")
	require.NotContains(t, output.String(), "synthetic")
	require.NotContains(t, output.String(), "Local prose")
}

func TestConnectorDevelopmentPublicationRevalidatesNodePreparation(t *testing.T) {
	t.Parallel()
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node.js is required for shared publication conformance")
	}
	actualRuntime, err := filepath.Abs("../../actions/setup/js/connector_runtime.cjs")
	require.NoError(t, err)
	actualContent, err := filepath.Abs("../../actions/setup/js/connector_content.cjs")
	require.NoError(t, err)
	runtimeJSON, err := json.Marshal(actualRuntime)
	require.NoError(t, err)
	for _, test := range []struct {
		name, mutation, expected string
	}{
		{"arguments", `args.issue = "UNAPPROVED";`, "outside approved resources"},
		{"intent", `result.request.digest = "mismatched";`, "does not match Go revalidation"},
	} {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			runtimePath := filepath.Join(root, "connector_runtime.cjs")
			require.NoError(t, os.WriteFile(runtimePath, []byte(`
const runtime = require(`+string(runtimeJSON)+`);
module.exports = {
  ...runtime,
  async executeConnector(encoded, capability, name, args, options) {
    const result = await runtime.executeConnector(encoded, capability, name, args, options);
    `+test.mutation+`
    return result;
  },
};`), 0600))
			require.NoError(t, os.Symlink(actualContent, filepath.Join(root, "connector_content.cjs")))
			declaration := loadDevelopmentConnector(t, developmentPublicationFixture(), map[string][]string{"issues": {"ISSUE-1"}})
			options := developmentOptions("safe-output", "add-note", `{"issue":"ISSUE-1","heading":"An actual publication title","text":"Local prose"}`)
			options.timeout = 20 * time.Second
			options.nodeRuntime = runtimePath
			var output bytes.Buffer
			err := testDevelopmentConnector(t.Context(), &output, declaration, options, nil, nil)
			require.ErrorContains(t, err, test.expected)
			require.Empty(t, output.String())
		})
	}
}
