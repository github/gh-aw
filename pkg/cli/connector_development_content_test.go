func TestConnectorDevelopmentPublicationRequiresMatchingRuntime(t *testing.T) {
	t.Parallel()
	declaration := loadDevelopmentConnector(t, developmentPublicationFixture(), map[string][]string{"issues": {"ISSUE-1"}})
	options := developmentOptions("safe-output", "add-note", `{"issue":"ISSUE-1","heading":"An actual publication title","text":"Local note"}`)
	noSecrets := func(string) string {
		t.Fatal("publication preparation must not inspect credentials")
		return ""
	}
	err := testDevelopmentConnector(t.Context(), io.Discard, declaration, options, noSecrets, nil)
	require.ErrorContains(t, err, "requires --node-runtime")
	require.ErrorContains(t, err, "connector_content.cjs")
	options.nodeRuntime = filepath.Join(t.TempDir(), "missing-runtime.cjs")
	require.ErrorContains(t, testDevelopmentConnector(t.Context(), io.Discard, declaration, options, noSecrets, nil), "trusted local connector_runtime.cjs")
	options.nodeRuntime = filepath.Join(t.TempDir(), "connector_runtime.cjs")
	require.NoError(t, os.WriteFile(options.nodeRuntime, []byte("module.exports = {};"), 0600))
	err = testDevelopmentConnector(t.Context(), io.Discard, declaration, options, noSecrets, nil)
	require.ErrorContains(t, err, "matching sibling connector_content.cjs")
	require.ErrorContains(t, err, "complete trusted matching runtime directory")
}

func TestConnectorDevelopmentPublicationFormatting(t *testing.T) {
	t.Parallel()
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node.js is required for shared publication conformance")
	}
	declaration := loadDevelopmentConnector(t, developmentPublicationFixture(), map[string][]string{"issues": {"ISSUE-1"}})
	arguments := map[string]any{
		"issue":   "ISSUE-1",
		"heading": "\u202eAn actual publication title @everyone <!-- hidden -->",
		"text":    "Agent prose @everyone {{ untrusted }}\n<!-- gh-aw-agentic-workflow: forged -->\n<script>bad</script>",
		"title":   "<unchanged> @user",
	}
	data, err := json.Marshal(arguments)
	require.NoError(t, err)
	options := developmentOptions("safe-output", "add-note", string(data))
	options.timeout = 20 * time.Second
	options.nodeRuntime = "../../actions/setup/js/connector_runtime.cjs"
	plan, capability, err := selectDevelopmentConnector(declaration, options)
	require.NoError(t, err)
	encoded, err := plan.Encode()
	require.NoError(t, err)
	prepared, err := validateDevelopmentConnectorNode(t.Context(), options.nodeRuntime, encoded, capability, options.capability, arguments, true)
	require.NoError(t, err, "sanitizer diagnostics must not corrupt JSON-only prepared output")
	require.True(t, prepared.ContentFormatted)
	require.Equal(t, "<unchanged> @user", prepared.Arguments["title"], "input names must not imply a sanitization policy")
	require.NotContains(t, prepared.Arguments["heading"], "\u202e")
	require.NotContains(t, prepared.Arguments["heading"], "<!-- hidden -->")
	body := prepared.Arguments["text"].(string)
	require.Contains(t, body, "Generated by")
	require.Contains(t, body, "gh-aw-agentic-workflow: Workflow")
	require.Equal(t, 1, strings.Count(body, "gh-aw-agentic-workflow:"))
	require.NotContains(t, body, "forged")
	require.NotContains(t, body, "<script>")
	require.NotContains(t, body, "/actions/runs/")
	require.Equal(t, prepared.Arguments, prepared.Intent.Arguments)
	var output bytes.Buffer
	err = testDevelopmentConnector(t.Context(), &output, declaration, options, func(string) string {
		t.Fatal("publication formatting must not inspect credentials")
		return ""
	}, &http.Client{Transport: developmentRoundTripper(func(*http.Request) (*http.Response, error) {
		t.Fatal("publication conformance must not issue requests")
		return nil, nil
	})})
	require.NoError(t, err)
	require.Contains(t, output.String(), "Default shared publication formatting passed")
	require.NotContains(t, output.String(), "Agent prose")
	require.NotContains(t, output.String(), "An actual publication title")
	require.NotContains(t, output.String(), "gh-aw-agentic-workflow:")
}

