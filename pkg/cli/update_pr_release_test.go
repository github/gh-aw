func TestUpdatePRTitle(t *testing.T) {
	originalVersion := GetVersion()
	t.Cleanup(func() { SetVersionInfo(originalVersion) })
	for _, version := range []struct{ input, want string }{
		{"1.2.3", "v1.2.3"},
		{"v1.2.3", "v1.2.3"},
		{"v1.2.3-beta.1", "v1.2.3-beta.1"},
		{"dev", "vdev"},
		{"", "vdev"},
	} {
		SetVersionInfo(version.input)
		for _, title := range []string{"Update workflows from source", "Upgrade agentic workflows"} {
			assert.Equal(t, title+" (gh aw "+version.want+")", updatePRTitle(title))
		}
	}
}

func TestExtractUpdatePRReleaseHighlights(t *testing.T) {
	for _, tc := range []struct{ name, body, want string }{
		{
			"curated section",
			"## \U0001f31f Release Highlights\r\n\r\nA useful release.\r\n\r\n### What's New\r\n\r\n- New feature.\r\n\r\n> Generated by release workflow\r\n\r\n<!-- gh-aw-agentic-workflow: Release -->\r\n\r\n---\r\n\r\n## What's Changed\r\n\r\n- Full changelog.",
			"## \U0001f31f Release Highlights\n\nA useful release.\n\n### What's New\n\n- New feature.",
		},
		{"next heading", "## Release Highlights\n\nSummary.\n\n## What's Changed\n\nChangelog.", "## Release Highlights\n\nSummary."},
		{"plain heading", "# Release Highlights\n\nSummary.", "# Release Highlights\n\nSummary."},
		{"metadata", "## Release Highlights\n\nSummary.\n\n<!-- gh-aw-agentic-workflow: Release -->", "## Release Highlights\n\nSummary."},
		{"separator", "## Release Highlights\n\nSummary.\n\n---\n\nChangelog.", "## Release Highlights\n\nSummary."},
		{"no highlights", "## What's Changed\n\n- Commit list.", ""},
		{"empty release", "", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, err := extractUpdatePRReleaseHighlights(tc.body)
			require.NoError(t, err)
			assert.Equal(t, tc.want, got)
		})
	}
}

func TestUpdateUpgradePRReleaseBody(t *testing.T) {
	originalVersion := GetVersion()
	t.Cleanup(func() { SetVersionInfo(originalVersion) })
	t.Chdir(t.TempDir())
	output, err := exec.Command("git", "init", "-q").CombinedOutput()
	require.NoError(t, err, "%s", output)
	summary, err := newUpdatePRSummary(context.Background(), ".github/workflows")
	require.NoError(t, err)

	for _, command := range []string{"update", "upgrade"} {
		t.Run(command, func(t *testing.T) {
			for _, tc := range []struct {
				name, version, response, want, warning string
				fail                                   bool
			}{
				{name: "stable", version: "1.2.3", response: `{"body":"## Release Highlights\n\n- Useful feature.\n\n## What's Changed\n\n- Commit list."}`, want: "- Useful feature."},
				{name: "prerelease", version: "v1.2.3-beta.1", response: `{"body":"## Release Highlights\n\n- Preview feature."}`, want: "- Preview feature."},
				{name: "no curated highlights", version: "v1.2.3", response: `{"body":"## What's Changed\n\n- Commit list."}`},
				{name: "lookup failure", version: "v1.2.3", fail: true, warning: "Could not load gh-aw release highlights"},
				{name: "malformed response", version: "v1.2.3", response: `{`, warning: "decoding release v1.2.3"},
				{name: "development", version: "dev"},
				{name: "unreleased describe", version: "v1.2.3-4-gabcd"},
				{name: "dirty build", version: "v1.2.3-dirty"},
			} {
				t.Run(tc.name, func(t *testing.T) {
					SetVersionInfo(tc.version)
					argsFile := filepath.Join(t.TempDir(), "gh-args")
					t.Setenv("GH_ARGS_FILE", argsFile)
					t.Setenv("RELEASE_RESPONSE", tc.response)
					script := "printf '%s\\n' \"$@\" > \"$GH_ARGS_FILE\"\nprintf '%s' \"$RELEASE_RESPONSE\"\n"
					if tc.fail {
						script += "exit 1\n"
					}
					prependFakeGH(t, script)
					var body string
					stderr := captureUpdateOrgStderr(t, func() {
						body, err = summary.body(context.Background(), command)
						body = appendUpdatePRReleaseHighlights(context.Background(), body)
					})
					require.NoError(t, err)
					link := summaryReleaseLink(ghawReleaseRepo, normalizeDisplayVersion(tc.version))
					if link == "" {
						assert.NoFileExists(t, argsFile, "unreleased builds must not request release notes")
						assert.NotContains(t, body, "/releases/tag/")
					} else {
						args, err := os.ReadFile(argsFile)
						require.NoError(t, err)
						assert.Equal(t, "api\n--hostname\ngithub.com\nrepos/github/gh-aw/releases/tags/"+normalizeDisplayVersion(tc.version)+"\n", string(args))
						assert.Contains(t, body, link)
					}
					if tc.want != "" {
						assert.Contains(t, body, "## Release Highlights\n\n"+tc.want)
					} else {
						assert.NotContains(t, body, "## Release Highlights")
					}
					assert.NotContains(t, body, "Commit list.")
					if tc.warning != "" {
						assert.Contains(t, stderr, tc.warning)
					} else {
						assert.Empty(t, stderr)
					}
				})
			}
		})
	}
}
