#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const project = path.join(root, "specs/otel");
const tempDir = mkdtempSync(path.join(os.tmpdir(), "gh-aw-otel-"));
const outputs = new Map([
  [path.join(root, "actions/setup/js/otel_attributes_generated.cjs"), "js"],
  [path.join(root, "pkg/workflow/otel_attributes_generated.go"), "go"],
]);

function compileSchema() {
  const tsp = path.join(project, "node_modules/.bin/tsp");
  execFileSync(tsp, ["compile", "attributes.tsp", "--emit", "@typespec/json-schema", "--option", "@typespec/json-schema.file-type=json", "--option", "@typespec/json-schema.seal-object-schemas=true", "--output-dir", tempDir], {
    cwd: project,
    stdio: "inherit",
  });
  const schemaPath = path.join(tempDir, "@typespec/json-schema/AttributeNames.json");
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  if (schema.type !== "object" || !schema.properties || !Array.isArray(schema.required)) {
    throw new Error("TypeSpec compiler emitted an unexpected AttributeNames schema");
  }
  const fields = Object.entries(schema.properties);
  if (!fields.length || schema.required.length !== fields.length || fields.some(([name, value]) => !schema.required.includes(name) || typeof value.const !== "string" || value.type !== "string")) {
    throw new Error("AttributeNames must contain required string literal properties");
  }
  if (new Set(fields.map(([, value]) => value.const)).size !== fields.length) {
    throw new Error("AttributeNames contains duplicate attribute values");
  }
  const names = fields.map(([name]) => name);
  const jsNames = names.map(name => `OTEL_ATTR_${name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase()}`);
  const goNames = names.map(name => `OTelAttr${name[0].toUpperCase()}${name.slice(1)}`);
  if (new Set(jsNames).size !== jsNames.length || new Set(goNames).size !== goNames.length) {
    throw new Error("AttributeNames generated identifiers must be unique");
  }
  const values = new Set(fields.map(([, value]) => value.const));
  const emitterSources = ["actions/setup/js/send_otlp_span.cjs", "actions/setup/js/send_otlp_session_logs.cjs"].map(file => readFileSync(path.join(root, file), "utf8"));
  const emittedNames = new Set();
  for (const source of emitterSources) {
    for (const match of source.matchAll(/build(?:Double|Array)?Attr\(\s*"([^"]+)"/g)) emittedNames.add(match[1]);
    for (const match of source.matchAll(/\[\s*"((?:gh-aw|gen_ai|github|runner|service|deployment|exception)\.[A-Za-z0-9._-]+)"\s*,\s*"[^"]+"\s*\]/g)) emittedNames.add(match[1]);
  }
  const queueSource = readFileSync(path.join(root, "actions/setup/js/work_queue_telemetry.cjs"), "utf8");
  const queuePrefix = queueSource.match(/const PREFIX = "([^"]+)"/)?.[1];
  if (!queuePrefix) throw new Error("Could not find work-queue telemetry attribute prefix");
  for (const match of queueSource.matchAll(/\$\{PREFIX\}([^`$]+)`/g)) emittedNames.add(`${queuePrefix}${match[1]}`);
  for (const match of queueSource.matchAll(/increment\(current,\s*"([^"]+)"/g)) emittedNames.add(`${queuePrefix}${match[1]}`);
  for (const match of queueSource.matchAll(/"((?:work|delivery|claims|reservations|capacity)\.[A-Za-z0-9._]+)"\s*:/g)) emittedNames.add(`${queuePrefix}${match[1]}`);
  for (const match of queueSource.matchAll(/\b(initialized|admission_paused|grants_paused):/g)) emittedNames.add(`${queuePrefix}${match[1]}`);
  const transitions = queueSource.match(/const TRANSITIONS = new Set\(\[([^\]]+)\]\)/)?.[1];
  if (!transitions) throw new Error("Could not find work-queue committed-operation names");
  for (const [, operation] of transitions.matchAll(/"([^"]+)"/g)) emittedNames.add(`${queuePrefix}committed.${operation}`);
  const missingNames = [...emittedNames].filter(name => !values.has(name));
  if (missingNames.length) {
    throw new Error(`TypeSpec is missing emitted attributes: ${missingNames.sort().join(", ")}`);
  }
  return fields;
}

function render(fields, target) {
  const words = name =>
    name
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .toUpperCase()
      .split("_");
  const jsNames = fields.map(([name]) => `OTEL_ATTR_${words(name).join("_")}`);
  const goNames = fields.map(([name]) => {
    const acronyms = { GITHUB: "GitHub", ID: "ID" };
    return `OTelAttr${words(name)
      .map(word => acronyms[word] ?? `${word[0]}${word.slice(1).toLowerCase()}`)
      .join("")}`;
  });

  if (target === "js") {
    return [
      "// Code generated by specs/otel/generate_attributes.mjs; DO NOT EDIT.",
      "",
      "const attributeNamesByValue = new Map([",
      ...fields.map(([, value]) => `  [${JSON.stringify(value.const)}, ${JSON.stringify(value.const)}],`),
      "]);",
      "",
      "module.exports = {",
      ...fields.map(([, value], index) => `  ${jsNames[index]}: ${JSON.stringify(value.const)},`),
      "  canonicalAttributeName: name => attributeNamesByValue.get(name) ?? name,",
      "};",
      "",
    ].join("\n");
  }

  const width = Math.max(...goNames.map(name => name.length));
  const goSource = [
    "// Code generated by specs/otel/generate_attributes.mjs; DO NOT EDIT.",
    "",
    "package workflow",
    "",
    "const (",
    ...fields.map(([, value], index) => `\t${goNames[index].padEnd(width)} = ${JSON.stringify(value.const)}`),
    ")",
    "",
    "var otelAttributeNamesByValue = map[string]string{",
    ...fields.map(([, value]) => `\t${JSON.stringify(value.const)}: ${JSON.stringify(value.const)},`),
    "}",
    "",
    "func canonicalOTelAttributeName(name string) string {",
    "\tif canonical, ok := otelAttributeNamesByValue[name]; ok {",
    "\t\treturn canonical",
    "\t}",
    "\treturn name",
    "}",
    "",
  ].join("\n");
  return execFileSync("gofmt", [], { encoding: "utf8", input: goSource });
}

try {
  const fields = compileSchema();
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [file, target] of outputs) {
    const expected = render(fields, target);
    if (check) {
      if (readFileSync(file, "utf8") !== expected) stale.push(path.relative(root, file));
    } else {
      writeFileSync(file, expected);
    }
  }
  if (stale.length) {
    console.error(`Generated OTEL attribute constants are stale: ${stale.join(", ")}`);
    console.error("Run npm run generate --prefix specs/otel");
    process.exitCode = 1;
  }
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
