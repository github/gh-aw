#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const project = path.join(root, "specs/otel");
const tempDir = mkdtempSync(path.join(os.tmpdir(), "gh-aw-otel-"));
const outputs = new Map([
  [path.join(root, "actions/setup/js/otel_attributes_generated.cjs"), "js"],
  [path.join(root, "pkg/workflow/otel_attributes_generated.go"), "go"],
]);

function compileSchema() {
  const tsp = path.join(project, "node_modules/.bin/tsp");
  execFileSync(tsp, ["compile", "attributes.tsp", "--emit", "@typespec/json-schema", "--option", "@typespec/json-schema.file-type=json", "--option", "@typespec/json-schema.seal-object-schemas=true", "--output-dir", tempDir], {
    cwd: project,
    stdio: "inherit",
  });
  const schemaPath = path.join(tempDir, "@typespec/json-schema/AttributeNames.json");
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  if (schema.type !== "object" || !schema.properties || !Array.isArray(schema.required)) {
    throw new Error("TypeSpec compiler emitted an unexpected AttributeNames schema");
  }
  const fields = Object.entries(schema.properties);
  if (!fields.length || schema.required.length !== fields.length || fields.some(([name, value]) => !schema.required.includes(name) || typeof value.const !== "string" || value.type !== "string")) {
    throw new Error("AttributeNames must contain required string literal properties");
  }
  if (new Set(fields.map(([, value]) => value.const)).size !== fields.length) {
    throw new Error("AttributeNames contains duplicate attribute values");
  }
  return fields;
}

function render(fields, target) {
  const words = name =>
    name
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .toUpperCase()
      .split("_");
  const jsNames = fields.map(([name]) => `OTEL_ATTR_${words(name).join("_")}`);
  const goNames = fields.map(([name]) => {
    const acronyms = { GITHUB: "GitHub", ID: "ID" };
    return `OTelAttr${words(name)
      .map(word => acronyms[word] ?? `${word[0]}${word.slice(1).toLowerCase()}`)
      .join("")}`;
  });

  if (target === "js") {
    return ["// Code generated by specs/otel/generate_attributes.mjs; DO NOT EDIT.", "", "module.exports = {", ...fields.map(([, value], index) => `  ${jsNames[index]}: ${JSON.stringify(value.const)},`), "};", ""].join("\n");
  }

  const width = Math.max(...goNames.map(name => name.length));
  return [
    "// Code generated by specs/otel/generate_attributes.mjs; DO NOT EDIT.",
    "",
    "package workflow",
    "",
    "const (",
    ...fields.map(([, value], index) => `\t${goNames[index].padEnd(width)} = ${JSON.stringify(value.const)}`),
    ")",
    "",
  ].join("\n");
}

try {
  const fields = compileSchema();
  const check = process.argv.includes("--check");
  const stale = [];
  for (const [file, target] of outputs) {
    const expected = render(fields, target);
    if (check) {
      if (readFileSync(file, "utf8") !== expected) stale.push(path.relative(root, file));
    } else {
      writeFileSync(file, expected);
    }
  }
  if (stale.length) {
    console.error(`Generated OTEL attribute constants are stale: ${stale.join(", ")}`);
    console.error("Run npm run generate --prefix specs/otel");
    process.exitCode = 1;
  }
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
