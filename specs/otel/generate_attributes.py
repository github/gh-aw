#!/usr/bin/env python3
"""Generate JavaScript and Go OpenTelemetry attribute names from TypeSpec."""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "specs/otel/attributes.tsp"
JS_OUTPUT = ROOT / "actions/setup/js/otel_attributes_generated.cjs"
GO_OUTPUT = ROOT / "pkg/workflow/otel_attributes_generated.go"


def generate():
    source = SOURCE.read_text()
    match = re.fullmatch(
        r"\s*namespace GH\.AW\.Telemetry;\s*model AttributeNames\s*\{([^}]*)\}\s*",
        source,
    )
    if not match:
        raise ValueError("unsupported TypeSpec: expected only AttributeNames model")

    fields = re.findall(r"\s*(\w+):\s*\"([a-zA-Z0-9._-]+)\";\s*", match[1])
    remaining = re.sub(r"\s*\w+:\s*\"[a-zA-Z0-9._-]+\";\s*", "", match[1])
    if not fields or remaining.strip():
        raise ValueError("unsupported AttributeNames model field")
    if len({name for name, _ in fields}) != len(fields):
        raise ValueError("duplicate TypeSpec attribute constant name")
    if len({value for _, value in fields}) != len(fields):
        raise ValueError("duplicate TypeSpec attribute value")

    def words(name):
        return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper().split("_")

    go_acronyms = {"GITHUB": "GitHub", "ID": "ID"}
    js_names = ["_".join(words(name)) for name, _ in fields]
    go_names = ["OTelAttr" + "".join(go_acronyms.get(word, word.title()) for word in words(name)) for name, _ in fields]
    js = [
        "// Code generated by specs/otel/generate_attributes.py; DO NOT EDIT.",
        "",
        "module.exports = {",
    ]
    js.extend(f'  OTEL_ATTR_{name}: "{value}",' for name, (_, value) in zip(js_names, fields))
    js.extend(["};", ""])

    go = [
        "// Code generated by specs/otel/generate_attributes.py; DO NOT EDIT.",
        "",
        "package workflow",
        "",
        "const (",
    ]
    name_width = max(map(len, go_names))
    go.extend(f'\t{name:<{name_width}} = "{value}"' for name, (_, value) in zip(go_names, fields))
    go.extend([")", ""])
    return {JS_OUTPUT: "\n".join(js), GO_OUTPUT: "\n".join(go)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        outputs = generate()
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1

    if args.check:
        drift = [str(path.relative_to(ROOT)) for path, content in outputs.items() if not path.exists() or path.read_text() != content]
        if drift:
            print("Generated OTEL attribute constants are stale: " + ", ".join(drift), file=sys.stderr)
            print("Run python3 specs/otel/generate_attributes.py", file=sys.stderr)
            return 1
        return 0

    for path, content in outputs.items():
        path.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
